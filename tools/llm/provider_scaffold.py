#!/usr/bin/env python3
# [TEMPLATE: CUI // SP-CTI]
"""Provider Scaffold — add a new LLM provider in one command.

Usage:
    python tools/llm/provider_scaffold.py --name cohere --type openai_compatible --api_key_env COHERE_API_KEY --base_url https://api.cohere.com/v1 --model_id command-r

    # Interactive mode (no args)
    python tools/llm/provider_scaffold.py

What it does:
    1. Validates inputs
    2. Generates a provider module (custom type only)
    3. Patches router.py _get_provider() factory (custom type only)
    4. Appends provider + model entries to args/llm_config.yaml
    5. Optionally adds the model to a routing chain
    6. Syncs new module to root tools/llm/ (custom type only)
    7. Runs live check_availability() + invoke() test
    8. Runs ruff check
    9. Prints a summary

Types:
    openai_compatible  -> reuses OpenAICompatibleProvider (no new module)
    ollama             -> reuses OllamaProvider (no new module)
    custom             -> generates a full provider class + patches router
"""

