# Router patching (custom type only)
# ---------------------------------------------------------------------------

def _patch_router(provider_name: str, class_name: str, module_file: str, ptype: str) -> None:
    """Insert a new elif branch into _get_provider()."""
    router_text = ROUTER_PATH.read_text(encoding="utf-8")

    # Check if already present
    if f'ptype == "{ptype}"' in router_text or f'ptype == "{provider_name}"' in router_text:
        print(f"  Router already has branch for {ptype}/{provider_name} — skipping patch")
        return

    # Build the new elif block
    block = f'''
            elif ptype == "{ptype}":
                from tools.llm.{module_file} import {class_name}

                api_key = self._get_byok_key(user_id, provider_name)
                if not api_key:
                    api_key = _expand_env(provider_cfg.get("api_key", ""))
                    if not api_key:
                        api_key_env = provider_cfg.get("api_key_env", "")
                        if api_key_env:
                            api_key = os.environ.get(api_key_env, "")
                base_url = _expand_env(provider_cfg.get("base_url", ""))
                instance = {class_name}(api_key=api_key, base_url=base_url)
'''

    # Insert before the final `else:` in the try block
    # Look for the pattern:            else:
    #                                logger.warning("Unknown provider type: %s", ptype)
    pattern = r'(\n            else:\n                logger\.warning\("Unknown provider type: %s", ptype\)\n                return None)'
    match = re.search(pattern, router_text)
    if not match:
        # Fallback: look for generic else block near end of try
        pattern2 = r'(\n            else:\n                logger\.warning\("Unknown provider type)'
        match = re.search(pattern2, router_text)

    if not match:
        raise RuntimeError("Could not find insertion point in router.py — manual patch required")

    insert_pos = match.start()
    new_router = router_text[:insert_pos] + block + router_text[insert_pos:]
    ROUTER_PATH.write_text(new_router, encoding="utf-8")
    print(f"  Patched {ROUTER_PATH}")


# ---------------------------------------------------------------------------
# Config patching
# ---------------------------------------------------------------------------

def _patch_config(
    provider_name: str,
    ptype: str,
    api_key_env: str,
    base_url: str,
    model_id: str,
    chain_function: Optional[str] = None,
) -> None:
    cfg = _load_config()

    providers = cfg.get("providers", {})
    if provider_name not in providers:
        block_lines = [f"  {provider_name}:\n", f"    type: {ptype}\n"]
        if api_key_env:
            block_lines.append(f"    api_key_env: {api_key_env}\n")
        if base_url:
            block_lines.append(f"    base_url: {base_url}\n")
        block_lines.append("\n")
        _insert_yaml_block("providers", "".join(block_lines))
        print("  Inserted provider block into 'providers:'")
    else:
        print(f"  Provider '{provider_name}' already exists in config -- skipping provider block")

    models = cfg.get("models", {})
    model_name = model_id.split(":")[0].split("/")[-1].replace("-", "_").replace(".", "_")
    original_model_name = model_name
    counter = 1
    while model_name in models:
        model_name = f"{original_model_name}_{counter}"
        counter += 1

    if model_name not in models:
        block_lines = [
            f"  {model_name}:\n",
            f"    provider: {provider_name}\n",
            f'    model_id: "{model_id}"\n',
            "    max_output_tokens: 4096\n",
            "    supports_thinking: false\n",
            "    supports_tools: false\n",
            "    supports_structured_output: false\n",
            "    pricing: {input_per_1k: 0.0, output_per_1k: 0.0}\n",
            "\n",
        ]
        _insert_yaml_block("models", "".join(block_lines))
        print("  Inserted model block into 'models:'")
    else:
        print(f"  Model '{model_name}' already exists -- skipping model block")

    if chain_function:
        cfg = _load_config()
        routing = cfg.setdefault("routing", {})
        route = routing.setdefault(chain_function, {})
        chain = route.setdefault("chain", [])
        if model_name not in chain:
            chain.append(model_name)
            _save_config(cfg)
            print(f"  Added '{model_name}' to routing chain for '{chain_function}'")

    print(f"  Updated {CONFIG_PATH}")
    return model_name


# ---------------------------------------------------------------------------
# Root sync (custom type only)
# ---------------------------------------------------------------------------

def _sync_to_root(module_path: Path) -> None:
    dest = ROOT_TOOLS / module_path.name
    shutil.copy2(module_path, dest)
    print(f"  Synced {module_path.name} to root tools/llm/")


# ---------------------------------------------------------------------------
# Live test
# ---------------------------------------------------------------------------

def _run_live_test(model_name: str, user_id: str = "") -> bool:
    print(f"\n  Live test: probing '{model_name}' ...")
    try:
        # Import via icdev namespace
        sys.path.insert(0, str(REPO_ROOT))
        from icdev.tools.llm.router import LLMRouter
        from icdev.tools.llm.provider import LLMRequest

        router = LLMRouter()
        model_cfg = router._get_model_config(model_name)
        if not model_cfg:
            print(f"    FAIL: model '{model_name}' not found in router config")
            return False

        provider_name = model_cfg.get("provider", "")
        provider = router._get_provider(provider_name, user_id=user_id)
        if provider is None:
            print(f"    FAIL: provider '{provider_name}' could not be instantiated")
            return False

        model_id = model_cfg.get("model_id", "")
        avail = provider.check_availability(model_id)
        print(f"    check_availability('{model_id}') -> {avail}")
        if not avail:
            return False

        req = LLMRequest(messages=[{"role": "user", "content": "Say 'OK'"}])
        req.user_id = user_id
        resp = provider.invoke(req, model_id, model_cfg)
        content = getattr(resp, "content", "")
        print(f"    invoke() -> content length={len(content)} model_id={getattr(resp, 'model_id', '')}")
        if content:
            print("    PASS")
            return True
        print("    FAIL: empty response")
        return False
    except Exception as exc:
        print(f"    FAIL: {exc}")
        return False
    finally:
        try:
            sys.path.remove(str(REPO_ROOT))
        except ValueError:
            pass


# ---------------------------------------------------------------------------
# Ruff check
# ---------------------------------------------------------------------------

def _run_ruff(file_path: Path) -> bool:
    print(f"\n  Running ruff check on {file_path.name} ...")
    try:
        result = subprocess.run(
            [sys.executable, "-m", "ruff", "check", str(file_path)],
            capture_output=True,
            text=True,
            cwd=str(REPO_ROOT),
            timeout=60,
        )
        if result.returncode == 0:
            print("    PASS")
            return True
        print(f"    FAIL:\n{result.stdout}\n{result.stderr}")
        return False
    except FileNotFoundError:
        print("    SKIP: ruff not installed")
        return True
    except Exception as exc:
        print(f"    FAIL: {exc}")
        return False


