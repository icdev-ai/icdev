def _interactive() -> argparse.Namespace:
    print("=" * 60)
    print("  ICDEV™ LLM Provider Scaffold")
    print("=" * 60)
    name = _validate_name(_prompt("Provider name (lowercase, no spaces)"))
    ptype = _prompt_choose("Provider type", TYPES, "openai_compatible")
    api_key_env = _prompt("API key env var (e.g. COHERE_API_KEY)", "")
    base_url = _prompt("Base URL", "")
    model_id = _prompt("Model ID", f"{name}-model")
    add_to_chain = _prompt_bool("Add to a routing chain?", False)
    chain_function = ""
    if add_to_chain:
        chain_function = _prompt("Function name (e.g. code_generation)", "chat_response")
    test = _prompt_bool("Run live test?", True)
    return argparse.Namespace(
        name=name,
        type=ptype,
        api_key_env=api_key_env,
        base_url=base_url,
        model_id=model_id,
        chain_function=chain_function or None,
        test=test,
        interactive=True,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Add a new LLM provider to ICDEV™")
    parser.add_argument("--name", required=False, help="Provider logical name (lowercase, no spaces)")
    parser.add_argument("--type", choices=TYPES, default="openai_compatible", help="Provider implementation type")
    parser.add_argument("--api_key_env", default="", help="Environment variable name for the API key")
    parser.add_argument("--base_url", default="", help="API base URL")
    parser.add_argument("--model_id", default="", help="Model identifier")
    parser.add_argument("--chain_function", default=None, help="Add model to this routing chain")
    parser.add_argument("--no-test", action="store_true", help="Skip live availability test")
    parser.add_argument("--no-ruff", action="store_true", help="Skip ruff lint check")
    args = parser.parse_args()

    if not args.name:
        args = _interactive()
    else:
        args.name = _validate_name(args.name)
        if not args.model_id:
            args.model_id = f"{args.name}-model"

    provider_name = args.name
    ptype = args.type
    api_key_env = args.api_key_env
    base_url = args.base_url
    model_id = args.model_id
    chain_function = args.chain_function
    do_test = not getattr(args, "no_test", False) and args.test
    do_ruff = not getattr(args, "no_ruff", False)

    print(f"\nScaffolding provider: {provider_name} (type={ptype})")
    print(f"  model_id={model_id} api_key_env={api_key_env or '(none)'} base_url={base_url or '(none)'}")

    # Custom type: generate module + patch router
    module_path: Optional[Path] = None
    if ptype == "custom":
        class_name = "".join(part.capitalize() for part in provider_name.split("_")) + "Provider"
        module_file = f"{provider_name}_provider.py"
        module_path = ICDEV_PKG / module_file
        _generate_custom_module(provider_name, class_name, module_path)
        _patch_router(provider_name, class_name, module_file.replace(".py", ""), ptype)
        _sync_to_root(module_path)
        if do_ruff:
            _run_ruff(module_path)
    else:
        print(f"  Type '{ptype}' reuses existing generic provider — no new module needed")

    # Patch config (all types)
    model_name = _patch_config(provider_name, ptype, api_key_env, base_url, model_id, chain_function)

    # Live test
    test_ok = False
    if do_test:
        test_ok = _run_live_test(model_name)

    # Summary
    print("\n" + "=" * 60)
    print("  SUMMARY")
    print("=" * 60)
    print(f"  Provider name : {provider_name}")
    print(f"  Type          : {ptype}")
    print(f"  Model config  : {model_name} -> {model_id}")
    if module_path:
        print(f"  Module        : {module_path.relative_to(REPO_ROOT)}")
        print(f"  Synced to     : root tools/llm/{module_path.name}")
    if chain_function:
        print(f"  Routing chain : added to '{chain_function}'")
    print(f"  Config file   : {CONFIG_PATH.relative_to(REPO_ROOT)}")
    if do_test:
        print(f"  Live test     : {'PASS' if test_ok else 'FAIL'}")
    print()
    print("  Next steps:")
    print(f"    1. Set your API key: export {api_key_env}=your_key")
    print("    2. Restart the dashboard so the new config is picked up")
    print("    3. Verify: python -c \"from icdev.tools.llm.router import LLMRouter; r=LLMRouter(); print(r.get_chain_for_function('chat_response'))\"")
    print()
    return 0 if (not do_test or test_ok) else 1


if __name__ == "__main__":
    sys.exit(main())
