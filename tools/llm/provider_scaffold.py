TYPES = ["openai_compatible", "ollama", "custom"]


def _prompt(text: str, default: str = "") -> str:
    if default:
        out = input(f"{text} [{default}]: ").strip()
        return out if out else default
    return input(f"{text}: ").strip()


def _prompt_choose(text: str, choices: list[str], default: str = "") -> str:
    while True:
        out = _prompt(f"{text} ({', '.join(choices)})", default)
        if out in choices:
            return out
        print(f"  Invalid choice. Must be one of: {', '.join(choices)}")


def _prompt_bool(text: str, default: bool = False) -> bool:
    suffix = " [Y/n]" if default else " [y/N]"
    out = input(f"{text}{suffix}: ").strip().lower()
    if not out:
        return default
    return out.startswith("y")


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------

def _validate_name(name: str) -> str:
    name = name.strip().lower()
    if not re.match(r"^[a-z][a-z0-9_]*$", name):
        raise ValueError("Provider name must be lowercase a-z, 0-9, underscores. First char must be a-z.")
    return name


def _load_config() -> dict:
    if yaml is None:
        raise RuntimeError("PyYAML required: pip install pyyaml")
    with open(CONFIG_PATH, "r", encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def _save_config(cfg: dict) -> None:
    with open(CONFIG_PATH, "w", encoding="utf-8") as f:
        yaml.dump(cfg, f, default_flow_style=False, sort_keys=False, allow_unicode=True)


def _insert_yaml_block(section_name: str, block_text: str) -> None:
    """Insert a block into a YAML section while preserving comments and order.

    Finds the *section_name* top-level key, then inserts *block_text*
    immediately before the next top-level key (or at end of file).
    """
    lines = CONFIG_PATH.read_text(encoding="utf-8").splitlines(keepends=True)
    in_section = False
    insert_idx = len(lines)
    for i, line in enumerate(lines):
        if not in_section:
            if line.strip().startswith(section_name + ":"):
                in_section = True
            continue
        # Inside section; look for next top-level key (no leading spaces)
        if line and not line.startswith(" ") and not line.startswith("#"):
            insert_idx = i
            break
    lines.insert(insert_idx, block_text)
    CONFIG_PATH.write_text("".join(lines), encoding="utf-8")


