class AdrRefused(Exception):
    """The register refuses the request. ``status`` is the HTTP status a route returns."""

    def __init__(self, status: int, code: str, message: str):
        self.status = status
        self.code = code
        self.message = message
        super().__init__(message)

    def to_dict(self) -> dict:
        return {"error": self.message, "code": self.code, "refused": True}


# ── configuration ────────────────────────────────────────────────────────────


def load_config(root: Optional[Path] = None) -> dict:
    """The ``adrs:`` block of ``args/coe_records.yaml``."""
    root = Path(root or BASE_DIR)
    data = yaml.safe_load((root / CONFIG_RELPATH).read_text(encoding="utf-8")) or {}
    cfg = dict(data.get("adrs") or {})
    for key in ("records_dir", "layout", "doc", "seed_identity"):
        if not cfg.get(key):
            raise ValueError(f"{CONFIG_RELPATH}: adrs.{key} is required")
    if not str(cfg["seed_identity"]).startswith("bootstrap:"):
        raise ValueError("adrs.seed_identity must be a labelled bootstrap identity ('bootstrap:...')")
    return cfg


def canonical(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), default=str)


def digest(value: Any) -> str:
    return hashlib.sha256(canonical(value).encode("utf-8")).hexdigest()


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%fZ")


def _text(value: Any) -> str:
    return str(value if value is not None else "").strip()


def _list(value: Any) -> list[str]:
    if isinstance(value, str):
        value = [v for v in re.split(r"[\s,]+", value) if v]
    return [_text(v) for v in value or [] if _text(v)]


# ── the record ───────────────────────────────────────────────────────────────


def normalise(entry: dict) -> dict:
    """An ADR's fields of record, in a fixed shape. What is digested and stored.

    Status and who recorded it are NOT here: they are the ledger's (and, in a
    record file, the export of it).
    """
    links = entry.get("links") or {}
    return {
        "id": _text(entry.get("id")),
        "title": " ".join(_text(entry.get("title")).split()),
        "version": _text(entry.get("version")) or "1",
        "section": _text(entry.get("section")),
        "format": _text(entry.get("format")) or "structured",
        "context": str(entry.get("context") or "").strip(),
        # The decision keeps its exact text: a legacy body is rendered verbatim.
        "decision": str(entry.get("decision") or "").rstrip("\n"),
        "consequences": str(entry.get("consequences") or "").strip(),
        "supersedes": sorted(set(_list(entry.get("supersedes")))),
        "links": {"requirements": sorted(set(_list(links.get("requirements")))),
                  "standards": sorted({s.upper() for s in _list(links.get("standards"))})},
    }


def entry_digest(entry: dict) -> str:
    return digest(normalise(entry))


def subject(adr_id: str, version: str) -> str:
    return f"adr:{adr_id}@{version}"


def derive_title(body: str) -> str:
    """A legacy ADR's title, from its text: the bold lead sentence when it has one,
    else the first clause. Derived, never rendered (the body is the record)."""
    first = body.split("\n", 1)[0].strip()
    m = re.match(r"^\*\*(.+?)\*\*", first)
    text = m.group(1) if m else re.split(r"(?:; | \(| — |\. )", first, maxsplit=1)[0]
    text = re.sub(r"[*`]", "", text).strip().rstrip(".:")
    return text[:157] + "..." if len(text) > 160 else text


def records_dir(root: Optional[Path] = None, cfg: Optional[dict] = None) -> Path:
    cfg = cfg or load_config(root)
    return Path(root or BASE_DIR) / cfg["records_dir"]


def write_record(path: Path, record: dict) -> None:
    """One record file: YAML front matter, then the decision text."""
    front = {k: record[k] for k in ("id", "title", "version", "status", "section", "format",
                                    "supersedes", "superseded_by", "links", "context",
                                    "consequences", "recorded")}
    text = "---\n" + yaml.safe_dump(front, sort_keys=False, allow_unicode=True, width=100) + \
        "---\n" + record["decision"] + "\n"
    path.write_text(text, encoding="utf-8")


def read_record(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{path.name}: a record opens with YAML front matter")
    end = text.index("\n---\n", 4)
    front = yaml.load(text[4:end], Loader=_LOADER) or {}
    body = text[end + 5:]
    if body.endswith("\n"):
        body = body[:-1]
    front["decision"] = body
    front["_file"] = path.name
    return front


def load_records(root: Optional[Path] = None) -> dict[str, dict]:
    """Every record file: id -> record (front matter plus ``decision``)."""
    out: dict[str, dict] = {}
    for path in sorted(records_dir(root).glob("*.md")):
        if path.name.startswith("_"):
            continue
        rec = read_record(path)
        out[_text(rec.get("id"))] = rec
    return out


def load_layout(root: Optional[Path] = None) -> list[str]:
    cfg = load_config(root)
    return (Path(root or BASE_DIR) / cfg["layout"]).read_text(encoding="utf-8").split("\n")


# ── rendering the flat doc ───────────────────────────────────────────────────


def render_record(rec: dict) -> str:
    """One ADR as the flat doc shows it.

    A legacy record is its body exactly as the flat doc had it; a later change
    of status is added as one line below it. A structured record shows its
    title, decision, context, consequences, status and links.
    """
    n = normalise(rec)
    status = _text(rec.get("status")) or "accepted"
    by = (rec.get("recorded") or {})
    if n["format"] == "legacy":
        out = f"- **{n['id']}:** {n['decision']}"
        if status != "accepted":
            out += "\n\n  " + _status_line(n, status, rec, by)
        return out
    title = n["title"].rstrip(".")
    out = f"- **{n['id']}:** **{title}.** {n['decision']}"
    if n["context"]:
        out += f"\n\n  *Context:* {n['context']}"
    if n["consequences"]:
        out += f"\n\n  *Consequences:* {n['consequences']}"
    out += "\n\n  " + _status_line(n, status, rec, by)
    return out


def _status_line(n: dict, status: str, rec: dict, by: dict) -> str:
    parts = [f"*Status:* {status}, version {n['version']}"]
    if rec.get("superseded_by"):
        parts.append(f"superseded by {rec['superseded_by']}")
    if n["supersedes"]:
        parts.append(f"supersedes {', '.join(n['supersedes'])}")
    if n["links"]["requirements"]:
        parts.append(f"requirements {', '.join(n['links']['requirements'])}")
    if n["links"]["standards"]:
        parts.append(f"standards {', '.join(n['links']['standards'])}")
    if by.get("by"):
        who = f"{by['by']} ({by.get('kind') or 'person'})"
        parts.append(f"recorded by {who}" + (f", step `{by['step_id']}`" if by.get("step_id") else ""))
    return "; ".join(parts) + "."


def render(records: dict[str, dict], layout: list[str], *, banner: bool = True) -> str:
    """The flat doc from the records and the layout. Raises ValueError on a
    placeholder with no record or a record placed twice or not at all."""
    out: list[str] = [BANNER] if banner else []
    placed: set[str] = set()
    for line in layout:
        m = _PLACEHOLDER.match(line)
        if not m:
            out.append(line)
            continue
        adr_id = m.group(1)
        if adr_id not in records:
            raise ValueError(f"the layout places {adr_id}, which has no record")
        if adr_id in placed:
            raise ValueError(f"the layout places {adr_id} twice")
        placed.add(adr_id)
        out.append(render_record(records[adr_id]))
    unplaced = sorted(set(records) - placed)
    if unplaced:
        raise ValueError(f"records the layout does not place: {', '.join(unplaced)}")
    return "\n".join(out)


def generate(root: Optional[Path] = None) -> str:
    return render(load_records(root), load_layout(root))


def check_doc(root: Optional[Path] = None) -> dict:
    """Does the committed flat doc equal what the records generate?"""
    root = Path(root or BASE_DIR)
    cfg = load_config(root)
    doc = root / cfg["doc"]
    try:
        want = generate(root)
    except (OSError, ValueError, yaml.YAMLError) as exc:
        return {"ok": False, "doc": cfg["doc"], "error": f"the records do not render: {exc}"}
    try:
        have = doc.read_text(encoding="utf-8")
    except OSError as exc:
        return {"ok": False, "doc": cfg["doc"], "error": f"{cfg['doc']} unreadable: {exc}"}
    if have == want:
        return {"ok": True, "doc": cfg["doc"], "sha256": hashlib.sha256(have.encode()).hexdigest()}
    a, b = have.split("\n"), want.split("\n")
    first = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
    return {"ok": False, "doc": cfg["doc"], "first_difference_line": first + 1,
            "error": (f"{cfg['doc']} has drifted from the ADR records (first difference at line "
                      f"{first + 1}). It is generated: add or change a record under "
                      f"{cfg['records_dir']}/ (and its line in _layout.md), then run "
                      "python tools/idp/adrs.py --write")}


def write_doc(root: Optional[Path] = None) -> dict:
    root = Path(root or BASE_DIR)
    cfg = load_config(root)
    text = generate(root)
    (root / cfg["doc"]).write_text(text, encoding="utf-8")
    return {"written": cfg["doc"], "sha256": hashlib.sha256(text.encode()).hexdigest()}


# ── the one-off migration from the flat doc ──────────────────────────────────


def parse_flat(text: str) -> tuple[list[str], list[dict]]:
    """Split a flat ADR doc into its layout lines and its ADRs, losslessly.

    An ADR is a ``- **<ID>:** `` line plus every following line that is indented,
    and every blank line that is followed by an indented one. Everything else is
    layout. ``render`` of the result (without the banner) gives *text* back.
    """
    lines = text.split("\n")
    layout: list[str] = []
    adrs: list[dict] = []
    section = ""
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("#"):
            section = line.lstrip("#").strip()
        m = _ADR_LINE.match(line)
        if not m:
            layout.append(line)
            i += 1
            continue
        body = [m.group(2)]
        j = i + 1
        while j < len(lines):
            nxt = lines[j]
            if nxt[:1] in (" ", "\t"):
                body.append(nxt)
                j += 1
                continue
            if nxt == "":
                k = j
                while k < len(lines) and lines[k] == "":
                    k += 1
                if k < len(lines) and lines[k][:1] in (" ", "\t"):
                    body.extend(lines[j:k])
                    j = k
                    continue
            break
        adrs.append({"id": m.group(1), "decision": "\n".join(body), "section": section})
        layout.append("{{adr " + m.group(1) + "}}")
        i = j
    return layout, adrs


def migrate_from_doc(flat: Path, root: Optional[Path] = None) -> dict:
    """Write one record per ADR of *flat* and the layout. Refuses to overwrite."""
    root = Path(root or BASE_DIR)
    cfg = load_config(root)
    text = flat.read_text(encoding="utf-8")
    layout, adrs = parse_flat(text)
    ids = [a["id"] for a in adrs]
    dupes = sorted({x for x in ids if ids.count(x) > 1})
    if dupes:
        raise ValueError(f"ADR ids declared twice in {flat}: {', '.join(dupes)}")
    out_dir = records_dir(root, cfg)
    if out_dir.exists() and any(out_dir.glob("*.md")):
        raise ValueError(f"{out_dir} already holds records: the migration runs once")
    out_dir.mkdir(parents=True, exist_ok=True)
    records = {}
    for a in adrs:
        rec = {"id": a["id"], "title": derive_title(a["decision"]), "version": "1",
               "status": "accepted", "section": a["section"], "format": "legacy",
               "supersedes": [], "superseded_by": "",
               "links": {"requirements": [], "standards": []},
               "context": "", "consequences": "",
               "recorded": {"by": cfg["seed_identity"], "kind": "bootstrap", "step_id": "",
                            "note": f"migrated from {cfg['doc']} at {cfg['migrated_from']['commit']}"},
               "decision": a["decision"]}
        write_record(out_dir / f"{a['id']}.md", rec)
        records[a["id"]] = rec
    (root / cfg["layout"]).write_text("\n".join(layout), encoding="utf-8")
    again = render(load_records(root), load_layout(root), banner=False)
    if again != text:
        raise ValueError("the migration is not lossless: the records do not render the flat doc")
    return {"records": len(adrs), "layout": cfg["layout"], "lossless": True}


# ── what a record may link to ────────────────────────────────────────────────


def requirement_ids(root: Optional[Path] = None) -> set[str]:
    """Every requirement id in ICDEV's platform model (args/platform_model/*.yaml)."""
    out: set[str] = set()
    for path in sorted((Path(root or BASE_DIR) / PLATFORM_MODEL_DIR).glob("*.yaml")):
        try:
            data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        except (OSError, yaml.YAMLError):
            continue
        out.update(_text(r.get("id")) for r in data.get("requirements") or [] if r.get("id"))
    return out


def standard_ids(conn=None) -> set[str]:
    """Every engineering standard id the register knows (seeds and ledger)."""
    from tools.idp.exemptions import standard_entries

    return set(standard_entries(conn))


def validate_entry(entry: dict, *, known_adrs: Iterable[str] = (), root: Optional[Path] = None,
                   conn=None, structured: bool = True, reqs: Optional[set[str]] = None,
                   stds: Optional[set[str]] = None) -> list[str]:
    """Shape and link errors for one ADR entry. Empty when it is well formed.

    ``reqs`` and ``stds`` are the known requirement and standard ids, when the
    caller has read them once for many entries.
    """
    n = normalise(entry)
    aid = n["id"] or "<no id>"
    errors = []
    # A migrated ADR keeps the id the flat doc gave it (some are ranges, e.g. D257-D260).
    if not (_ID_RE if n["format"] == "structured" else _LEGACY_ID_RE).match(n["id"]):
        errors.append(f"{aid}: id must look like D-AREA-N (capitals, digits, dashes) or DN")
    if not n["title"]:
        errors.append(f"{aid}: title is required")
    if not n["decision"].strip():
        errors.append(f"{aid}: the decision is required")
    if structured and n["format"] == "structured":
        for field in ("context", "consequences"):
            if not n[field]:
                errors.append(f"{aid}: {field} is required (context, decision, consequences)")
    if n["format"] not in FORMATS:
        errors.append(f"{aid}: format is one of {', '.join(FORMATS)}")
    if n["links"]["requirements"] and reqs is None:
        reqs = requirement_ids(root)
    bad = [r for r in n["links"]["requirements"] if r not in (reqs or set())]
    if bad:
        errors.append(f"{aid}: not a platform-model requirement: {', '.join(bad)}")
    if n["links"]["standards"]:
        stds = standard_ids(conn) if stds is None else stds
        bad = [s for s in n["links"]["standards"] if s not in stds]
        if bad:
            errors.append(f"{aid}: not in the standards register: {', '.join(bad)}")
    known = set(known_adrs)
    bad = [s for s in n["supersedes"] if s not in known or s == n["id"]]
    if bad:
        errors.append(f"{aid}: supersedes an ADR that is not recorded: {', '.join(bad)}")
    return errors


def validate_records(root: Optional[Path] = None) -> list[str]:
    """Every record well formed, its status declared, its links real, the doc renders."""
    root = Path(root or BASE_DIR)
    errors: list[str] = []
    try:
        records = load_records(root)
        layout = load_layout(root)
    except (OSError, ValueError, yaml.YAMLError) as exc:
        return [f"the records cannot be read: {exc}"]
    reqs = requirement_ids(root)
    stds: Optional[set[str]] = None
    for aid, rec in records.items():
        if (rec.get("links") or {}).get("standards") and stds is None:
            stds = standard_ids()
        if _text(rec.get("status")) not in STATUSES:
            errors.append(f"{aid}: status is one of {', '.join(STATUSES)}")
        if _text(rec.get("_file")) != f"{aid}.md":
            errors.append(f"{aid}: lives in {rec.get('_file')}, not {aid}.md")
        by = rec.get("recorded") or {}
        if by.get("kind") not in ACTOR_KINDS or not _text(by.get("by")):
            errors.append(f"{aid}: recorded.by and recorded.kind (person, agent, bootstrap) say who")
        if by.get("kind") == "person" and not _text(by.get("step_id")):
            errors.append(f"{aid}: a person's record names the declared step that decided it")
        errors.extend(validate_entry(rec, known_adrs=records, root=root, reqs=reqs, stds=stds,
                                     structured=_text(rec.get("format")) == "structured"))
        if rec.get("superseded_by") and rec["superseded_by"] not in records:
            errors.append(f"{aid}: superseded by {rec['superseded_by']}, which has no record")
    try:
        render(records, layout)
    except ValueError as exc:
        errors.append(str(exc))
    return errors


# ── the ledger ───────────────────────────────────────────────────────────────


def _connection():
    """The platform database, without the row-security predicate.

    ``coe_adr_events`` has no tenant or classification column: ADRs are the
    platform's own engineering decisions, not marked data, and who may change
    them is held by the declared steps (the same reason as coe_standard_events).
    """
    from tools.db.storage import get_canvas_connection

    return get_canvas_connection()


def _row_hash(row: dict) -> str:
    return digest({k: row.get(k, "") for k in _HASHED})


def read_events(conn=None, adr_id: Optional[str] = None) -> list[dict]:
    """Every ledger row (or one ADR's), as stored. Raises when unreadable."""
    own = conn is None
    conn = conn or _connection()
    try:
        sql = f"SELECT {', '.join(_COLS)} FROM {TABLE}"  # nosec B608 — fixed table and columns
        params: tuple = ()
        if adr_id:
            sql += " WHERE adr_id = %s"
            params = (adr_id,)
        rows = conn.execute(sql + " ORDER BY created_at, event_id", params).fetchall()
    finally:
        if own:
            conn.close()
    return [dict(zip(_COLS, tuple(r))) for r in rows]


def chain(rows: Iterable[dict]) -> dict[str, Any]:
    """Order each ADR's rows along its hash chain and verify every link.

    ``{adr_id: [rows in chain order], "_problems": [...]}``.
    """
    by_id: dict[str, list[dict]] = {}
    for r in rows:
        by_id.setdefault(str(r["adr_id"]), []).append(r)
    out: dict[str, Any] = {"_problems": []}
    for aid, items in sorted(by_id.items()):
        nxt = {str(r["prev_hash"]): r for r in items}
        ordered, prev = [], GENESIS
        while prev in nxt:
            r = nxt.pop(prev)
            ordered.append(r)
            prev = str(r["row_hash"])
        for r in items:
            if _row_hash(r) != r["row_hash"]:
                out["_problems"].append({"event_id": r["event_id"], "adr_id": aid,
                                         "problem": "row hash does not match its content"})
            try:
                if digest(json.loads(r["entry_json"])) != r["entry_digest"]:
                    raise ValueError
            except (ValueError, TypeError):
                out["_problems"].append({"event_id": r["event_id"], "adr_id": aid,
                                         "problem": "entry does not match its digest"})
        for r in nxt.values():
            out["_problems"].append({"event_id": r["event_id"], "adr_id": aid,
                                     "problem": "not on the ADR's hash chain"})
        out[aid] = ordered
    return out


def _detail(row: dict) -> dict:
    try:
        return json.loads(row.get("detail_json") or "{}")
    except ValueError:
        return {}


def replay(ordered: list[dict]) -> dict:
    """One ADR's state from its rows in chain order. Pure.

    ``{versions, order, latest, in_force, history}``. A version's state is the
    last event on it; an accepted version a newer acceptance replaced reads
    ``superseded`` (by that version).
    """
    versions: dict[str, dict] = {}
    order: list[str] = []
    in_force: Optional[str] = None
    history = []
    for r in ordered:
        v = str(r["version"])
        entry = json.loads(r["entry_json"])
        det = _detail(r)
        rec = versions.get(v)
        if rec is None:
            rec = versions[v] = {"version": v, "entry": entry, "entry_digest": r["entry_digest"],
                                 "author": r["actor"], "author_kind": r["actor_kind"],
                                 "proposed_at": r["created_at"], "state": None,
                                 "superseded_by": ""}
            order.append(v)
        event = r["event"]
        state = det.get("state") if event == "seeded" else event
        if event == "returned":
            state = "returned"
        rec["state"] = state
        if state == "accepted":
            if in_force and in_force != v:
                versions[in_force]["state"] = "superseded"
                versions[in_force]["superseded_by"] = f"{entry.get('id')} version {v}"
            in_force = v
            rec.update(accepted_at=r["created_at"], accepted_by=r["actor"],
                       accepted_kind=r["actor_kind"], accepted_event=r["event_id"],
                       accepted_step=r["step_id"])
        if event in ("superseded", "deprecated") or state in ("superseded", "deprecated"):
            rec["superseded_by"] = det.get("superseded_by") or rec.get("superseded_by") or ""
            rec.update(closed_at=r["created_at"], closed_by=r["actor"], closed_step=r["step_id"])
            if in_force == v:
                in_force = None
        history.append({k: r[k] for k in ("event_id", "version", "event", "actor", "actor_kind",
                                          "actor_role", "step_id", "reason", "entry_digest",
                                          "created_at", "row_hash", "prev_hash")}
                       | {"state": state, "detail": det})
    latest = versions[order[-1]] if order else None
    return {"versions": versions, "order": order, "latest": latest, "in_force": in_force,
            "history": history}


def _append(conn, *, adr_id: str, version: str, event: str, actor: str, actor_kind: str,
            entry: dict, actor_role: str = "", step_id: str = "", reason: str = "",
            detail: Optional[dict] = None, prev_hash: str) -> dict:
    if event not in EVENTS or actor_kind not in ACTOR_KINDS:
        raise ValueError(f"bad event {event!r} or actor kind {actor_kind!r}")
    norm = normalise(entry)
    row = {"event_id": f"adr-{uuid.uuid4().hex[:16]}", "adr_id": adr_id, "version": version,
           "event": event, "actor": actor, "actor_kind": actor_kind,
           "actor_role": actor_role or "", "step_id": step_id or "", "reason": reason or "",
           "entry_digest": digest(norm), "entry_json": canonical(norm),
           "detail_json": canonical(detail or {}), "prev_hash": prev_hash, "created_at": _now()}
    row["row_hash"] = _row_hash(row)
    try:
        conn.execute(
            f"INSERT INTO {TABLE} ({', '.join(_COLS)}) VALUES ({', '.join(['%s'] * len(_COLS))})",
            tuple(row[c] for c in _COLS),
        )
        conn.commit()
    except Exception as exc:  # noqa: BLE001
        try:
            conn.rollback()     # PostgreSQL: the failed statement aborted the transaction
        except Exception:  # noqa: BLE001
            pass
        text = str(exc).lower()
        if "unique" in text or "duplicate" in text:
            raise AdrRefused(409, "concurrent", f"{adr_id} changed while you were deciding: "
                                                "reload it") from exc
        raise AdrRefused(503, "store_unavailable",
                         f"the ADR ledger could not be written, so nothing changed ({exc})") from exc
    return row


def _state(adr_id: str, conn) -> tuple[dict, list[dict]]:
    rows = read_events(conn, adr_id)
    ch = chain(rows)
    return replay(ch.get(adr_id, [])), ch["_problems"]


def _head(st: dict) -> str:
    return st["history"][-1]["row_hash"] if st["history"] else GENESIS


