# CUI // SP-CTI
"""Architecture decision records as signed, versioned records (icx-coe-02).

``docs/reference/adrs.md`` was one flat file of about 675 decisions that every
branch appended to by hand. It is now GENERATED from records:

* ``docs/reference/adrs/<ID>.md`` — one record per ADR: YAML front matter (id,
  title, version, status, section, supersedes, superseded_by, links to
  platform-model requirements and engineering standards, context, consequences,
  and who recorded it) and the decision text as the body;
* ``docs/reference/adrs/_layout.md`` — the flat doc's headings and prose, with
  one ``{{adr <ID>}}`` line where each ADR reads.

``python tools/idp/adrs.py --write`` renders the doc; ``--check`` fails when the
doc has drifted from the records (CI runs it). The migration was lossless: a
record migrated from the flat doc (``format: legacy``) renders its body exactly
as the flat doc had it, and ``tests/test_icx_coe_02_adrs.py`` regenerates the
doc as it stood at the migration from the records and compares it byte for byte.

THE LIFECYCLE is propose -> accept -> supersede (or deprecate), and status is
never a field anyone edits at runtime: it is the replay of ``coe_adr_events``,
an append-only, hash-chained ledger (``UNIQUE(adr_id, prev_hash)``).

* ``propose``    anyone, or an agent through MCP: a draft (a new ADR, or a new
                 version of one). It decides nothing.
* ``accept``     a person who is not the author accepts it or returns it
                 (``decl-wft-coe-adr-accept``), at the record digest read.
* ``supersede``  a person who wrote neither it nor its successor supersedes it
                 by an accepted ADR, or deprecates it
                 (``decl-wft-coe-adr-supersede``).

The records are seeded into the ledger by the labelled bootstrap identity
(``seed``), never as a person's signature. A decision taken in the ledger
reaches the doc through ``--export <ID>`` (it writes the record from the ledger,
with the step that decided it), a reviewed commit, and ``--write``.

CLI::

    python tools/idp/adrs.py --write | --check [--json]
    python tools/idp/adrs.py --validate [--json]
    python tools/idp/adrs.py --list | --show D-COE-2 [--json]
    python tools/idp/adrs.py --seed [--json]
    python tools/idp/adrs.py --export D-COE-2
    python tools/idp/adrs.py --migrate-from-doc <flat.md>      (one-off; already run)
"""
