def twin_evidence(root: Optional[Path] = None) -> dict:
    """What the governance twin reads about the ADRs. Never raises."""
    root = Path(root or BASE_DIR)
    ev: dict[str, Any] = {"records": None, "ledger": None, "doc": None, "errors": {}}
    try:
        records = load_records(root)
        cfg = load_config(root)
        ev["records"] = {"count": len(records), "dir": cfg["records_dir"], "layout": cfg["layout"],
                         "statuses": {a: _text(r.get("status")) for a, r in records.items()},
                         "invalid": validate_records(root)[:20]}
        ev["doc"] = check_doc(root)
    except Exception as exc:  # noqa: BLE001 — unreadable is unverified
        ev["errors"]["records"] = str(exc)
        records = {}
    try:
        ch = chain(read_events())
    except Exception as exc:  # noqa: BLE001
        ev["errors"]["ledger"] = str(exc)
        return ev
    items = []
    for aid, ordered in sorted(ch.items()):
        if aid == "_problems" or not ordered:
            continue
        st = replay(ordered)
        latest = st["latest"] or {}
        items.append({"id": aid, "state": latest.get("state"), "version": latest.get("version"),
                      "last_event": st["history"][-1]["event_id"],
                      "last_at": st["history"][-1]["created_at"],
                      "seeded_only": all(h["event"] == "seeded" for h in st["history"])})
    ev["ledger"] = {"problems": ch["_problems"], "adrs": items}
    return ev


def twin_judge(ev: dict, policy: dict, observed_at: str) -> tuple[list[dict], list[dict], dict]:
    """``(checks, findings, summary)`` for the ADRs. Pure: replays from the evidence."""
    from tools.twin_core.governance import age_hours, check, finding

    errors = ev.get("errors") or {}
    recs, ledger, doc = ev.get("records"), ev.get("ledger"), ev.get("doc") or {}
    statuses = (recs or {}).get("statuses") or {}
    in_ledger = {a["id"] for a in (ledger or {}).get("adrs") or []}
    missing = sorted(set(statuses) - in_ledger)
    checks = [
        check("coe.adrs.records", "ADR records (docs/reference/adrs/)", recs is not None,
              errors.get("records") or "records not read"),
        check("coe.adrs.ledger", "ADR ledger (coe_adr_events)", ledger is not None,
              errors.get("ledger") or "ledger not read"),
        # An ADR the ledger has never seen is unverified, never passed.
        check("coe.adrs.recorded", "Every ADR record is in the ledger",
              recs is not None and ledger is not None and not missing,
              (f"{len(missing)} record(s) not in the ledger (e.g. {', '.join(missing[:3])}): "
               "unverified, not passed; run python tools/idp/adrs.py --seed") if missing
              else "the records or the ledger were not read"),
    ]
    findings = []
    for p in (ledger or {}).get("problems") or []:
        findings.append(finding(
            "coe.adr.chain_broken", "critical", f"{p['adr_id']}: {p['problem']}",
            thread_id=f"coe_adr:{p['event_id']}",
            recommendation="The history of this ADR cannot be trusted; find who wrote the row "
                           "(the ledger is append-only) and treat it as an incident."))
    if recs is not None and doc and not doc.get("ok"):
        findings.append(finding(
            "coe.adr.doc_drift", "high", "docs/reference/adrs.md has drifted from the ADR records",
            thread_id=f"config:{doc.get('doc') or 'docs/reference/adrs.md'}@",
            detail=str(doc.get("error") or ""),
            recommendation="Change a record, never the doc, and run python tools/idp/adrs.py --write."))
    for msg in (recs or {}).get("invalid") or []:
        findings.append(finding(
            "coe.adr.record_invalid", "medium", msg,
            thread_id=f"config:{(recs or {}).get('layout') or 'docs/reference/adrs/_layout.md'}@",
            recommendation="Fix the record: an ADR's links name real requirements and standards."))
    waiting_days = float(policy.get("adr_waiting_warn_days") or 14)
    for a in (ledger or {}).get("adrs") or []:
        rec_status = statuses.get(a["id"])
        state = a.get("state")
        if state in STATUSES and not a.get("seeded_only") and rec_status != state:
            findings.append(finding(
                "coe.adr.unexported", "low",
                f"{a['id']} is {state} in the ledger but "
                + (f"{rec_status} in its record" if rec_status else "has no record file"),
                thread_id=f"coe_adr:{a['last_event']}",
                recommendation=f"Run python tools/idp/adrs.py --export {a['id']} and --write, and "
                               "commit: the decision reaches the doc through a reviewed change."))
        if state == "proposed":
            age = age_hours(a.get("last_at"), observed_at)
            if age is not None and age > waiting_days * 24:
                findings.append(finding(
                    "coe.adr.proposed.waiting", "low",
                    f"{a['id']} {a['version']} has been proposed for {age / 24:.0f} days",
                    thread_id=f"coe_adr:{a['last_event']}",
                    recommendation="A person who is not the author accepts or returns it."))
    adrs = (ledger or {}).get("adrs") or []
    summary = {"adr_records": len(statuses), "adrs_in_ledger": len(in_ledger),
               "adrs_unrecorded": len(missing),
               "adrs_accepted_by_a_person": sum(1 for a in adrs if a.get("state") == "accepted"
                                                and not a.get("seeded_only")),
               "adr_doc_in_sync": bool(doc.get("ok")) if recs is not None else None}
    return checks, findings, summary


