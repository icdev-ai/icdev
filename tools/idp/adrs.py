def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="ADRs as signed, versioned records (icx-coe-02).")
    ap.add_argument("--write", action="store_true", help="generate docs/reference/adrs.md")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when docs/reference/adrs.md has drifted from the records")
    ap.add_argument("--validate", action="store_true", help="validate every record (no database)")
    ap.add_argument("--list", action="store_true", help="every ADR and its status")
    ap.add_argument("--show", metavar="ID", help="one ADR with its full history")
    ap.add_argument("--seed", action="store_true",
                    help="record ADR records not yet in the ledger (bootstrap identity)")
    ap.add_argument("--export", metavar="ID", help="write one ADR's record from the ledger")
    ap.add_argument("--migrate-from-doc", metavar="FLAT_MD",
                    help="one-off: split a flat ADR doc into records and the layout")
    ap.add_argument("--json", action="store_true", help="JSON output")
    args = ap.parse_args(argv)
    try:
        if args.check:
            out: Any = check_doc()
            print(json.dumps(out, indent=2) if args.json else
                  ("docs/reference/adrs.md matches the ADR records" if out["ok"] else out["error"]))
            return 0 if out["ok"] else 1
        if args.validate:
            errors = validate_records()
            out = {"valid": not errors, "errors": errors}
        elif args.write:
            out = write_doc()
        elif args.seed:
            out = seed()
        elif args.export:
            out = export(args.export)
        elif args.migrate_from_doc:
            out = migrate_from_doc(Path(args.migrate_from_doc))
        elif args.show:
            out = adr_view(args.show)
        else:
            out = adrs_view()
    except AdrRefused as exc:
        print(json.dumps(exc.to_dict(), indent=2))
        return 1
    if args.list and not args.json:
        for s in out["adrs"]:
            print(f"{s['id']:<14} {s['status'] or '-':<11} {'ledger' if s['in_ledger'] else 'record':<7} "
                  f"{s['title'][:80]}")
        return 0
    print(json.dumps(out, indent=2, default=str))
    return 0 if not (args.validate and out.get("errors")) else 1


if __name__ == "__main__":
    raise SystemExit(main())
