def main():
    parser = argparse.ArgumentParser(description="Genesis Goal Template Generator")
    parser.add_argument("--pattern-id", type=str, help="Generate goal from specific stored pattern")
    parser.add_argument(
        "--from-detection", action="store_true", help="Generate goals from all unprocessed detected patterns"
    )
    parser.add_argument("--max-goals", type=int, default=3)
    parser.add_argument("--min-score", type=float, default=0.0)
    parser.add_argument("--no-llm", action="store_true", help="Skip LLM polishing")
    parser.add_argument(
        "--llm-metadata",
        action="store_true",
        help="Use LLM to extract richer title/description/inputs/outputs/category",
    )
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    use_llm_meta = getattr(args, "llm_metadata", False)

    if args.from_detection:
        goals = generate_from_stored_patterns(
            max_goals=args.max_goals,
            min_score=args.min_score,
        )
        if use_llm_meta:
            goals = [
                generate_goal_from_pattern(
                    {
                        "pattern": g["tool_chain"],
                        "frequency": g["frequency"],
                        "caller_diversity": g["caller_diversity"],
                        "composite_score": g["composite_score"],
                    },
                    use_llm_metadata=True,
                )
                for g in goals
            ]
        if not args.no_llm:
            goals = [polish_with_llm(g) for g in goals]

        result = {
            "generated_at": _utcnow_iso(),
            "goals_generated": len(goals),
            "goals": goals,
        }
    elif args.pattern_id:
        conn = get_connection()
        try:
            row = conn.execute(
                "SELECT tool_chain, frequency, caller_diversity, composite_score "
                "FROM genesis_tool_patterns WHERE id = %s",
                (args.pattern_id,),
            ).fetchone()
            if not row:
                result = {"error": f"Pattern {args.pattern_id} not found"}
            else:
                pattern = {
                    "pattern": json.loads(row["tool_chain"] if isinstance(row, dict) else row[0]),
                    "frequency": row["frequency"] if isinstance(row, dict) else row[1],
                    "caller_diversity": row["caller_diversity"] if isinstance(row, dict) else row[2],
                    "composite_score": row["composite_score"] if isinstance(row, dict) else row[3],
                }
                goal = generate_goal_from_pattern(pattern, use_llm_metadata=use_llm_meta)
                if not args.no_llm:
                    goal = polish_with_llm(goal)
                result = {"generated_at": _utcnow_iso(), "goals_generated": 1, "goals": [goal]}
        finally:
            conn.close()
    else:
        result = {"error": "Specify --from-detection or --pattern-id"}

    if args.json:
        # Don't dump full markdown in JSON — include as field
        print(json.dumps(result, indent=2, default=str))
    else:
        for g in result.get("goals", []):
            print(g.get("goal_markdown", ""))
            print("---")


if __name__ == "__main__":
    main()
