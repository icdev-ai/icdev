# Batch generation from stored patterns
# ---------------------------------------------------------------------------


def generate_from_stored_patterns(
    max_goals: int = 3,
    min_score: float = 0.0,
) -> List[Dict[str, Any]]:
    """Generate goals from patterns stored in genesis_tool_patterns.

    Only processes patterns with status='detected' (not yet converted).
    """
    conn = get_connection()
    try:
        rows = conn.execute(
            """
            SELECT id, tool_chain, frequency, caller_diversity,
                   chain_length, composite_score, sessions
            FROM genesis_tool_patterns
            WHERE status = 'detected' AND composite_score >= %s
            ORDER BY composite_score DESC
            LIMIT %s
        """,
            (min_score, max_goals),
        ).fetchall()

        goals = []
        for row in rows:
            pattern = {
                "pattern": json.loads(row["tool_chain"] if isinstance(row, dict) else row[1]),
                "frequency": row["frequency"] if isinstance(row, dict) else row[2],
                "caller_diversity": row["caller_diversity"] if isinstance(row, dict) else row[3],
                "composite_score": row["composite_score"] if isinstance(row, dict) else row[5],
            }
            goal = generate_goal_from_pattern(pattern)
            goal = polish_with_llm(goal)
            goals.append(goal)

            # Mark pattern as processed
            pid = row["id"] if isinstance(row, dict) else row[0]
            conn.execute("UPDATE genesis_tool_patterns SET status = 'goal_generated' WHERE id = %s", (pid,))

        conn.commit()
        return goals
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


