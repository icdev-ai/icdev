def _main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    parser = argparse.ArgumentParser(
        description="ICDEV™ air-gap npm mirror sync (admin-only).",
    )
    parser.add_argument(
        "--pack", action="store_true",
        help="Snapshot node_modules + npm cache into vendor/npm/<snapshot>/",
    )
    parser.add_argument(
        "--unpack", action="store_true",
        help="Extract snapshot modules.tar.gz back to --dest",
    )
    parser.add_argument(
        "--verify", action="store_true",
        help="Verify SHA256 manifest for --snapshot",
    )
    parser.add_argument(
        "--list", action="store_true",
        help="List all snapshots in vendor/npm/",
    )
    parser.add_argument(
        "--gen-npmrc", action="store_true",
        help="Generate .npmrc for --snapshot (--strategy selects the approach)",
    )
    parser.add_argument(
        "--source", type=str, default="frontend/node_modules",
        help="node_modules path for --pack (default: frontend/node_modules)",
    )
    parser.add_argument(
        "--dest", type=str, default="vendor/npm",
        help="Vendor root for --pack, or target node_modules parent for --unpack",
    )
    parser.add_argument(
        "--cache", type=str, default=None,
        help="npm cache path for --pack (default: OS default ~/.npm / %%APPDATA%%\\npm-cache)",
    )
    parser.add_argument(
        "--snapshot", type=str, default=None,
        help="Snapshot name (required for --unpack, --verify, --gen-npmrc)",
    )
    parser.add_argument(
        "--strategy", type=str, default="offline-cache",
        choices=["offline-cache", "verdaccio", "tarball-deps"],
        help="Registry override strategy for --gen-npmrc (default: offline-cache)",
    )
    parser.add_argument("--json", action="store_true", help="JSON output")
    args = parser.parse_args()

    try:
        if args.list:
            out = list_snapshots()
        elif args.pack:
            source = (BASE_DIR / args.source).resolve()
            dest = (BASE_DIR / args.dest).resolve()
            cache = Path(args.cache).resolve() if args.cache else None
            out = pack(source=source, dest=dest, npm_cache=cache, snapshot=args.snapshot)
        elif args.unpack:
            if not args.snapshot:
                parser.error("--unpack requires --snapshot")
            dest = (BASE_DIR / args.dest).resolve()
            out = unpack(snapshot=args.snapshot, dest=dest)
        elif args.verify:
            if not args.snapshot:
                parser.error("--verify requires --snapshot")
            out = verify(snapshot=args.snapshot)
        elif args.gen_npmrc:
            if not args.snapshot:
                parser.error("--gen-npmrc requires --snapshot")
            out = gen_npmrc(snapshot=args.snapshot, strategy=args.strategy)
        else:
            parser.print_help()
            return 2
    except Exception as exc:
        if args.json:
            print(json.dumps({"ok": False, "error": str(exc)}, indent=2))
        else:
            print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps(out, indent=2, default=str))
    else:
        print(json.dumps(out, indent=2, default=str))
    return 0 if out.get("ok", True) else 1


if __name__ == "__main__":
    sys.exit(_main())
