# ── Seed Function ─────────────────────────────────────────────────────────────

def seed(dry_run: bool = False, category: str | None = None,
         status: str = "draft") -> dict:
    """Seed SOPs. Returns {"seeded": int, "skipped": int, "errors": list}."""
    init_db()

    existing = {s["title"] for s in list_sops(limit=2000)}
    to_seed = [s for s in ALL_SOPS if (category is None or s["category"] == category)]

    seeded = 0
    skipped = 0
    errors: list = []

    for sop in to_seed:
        if sop["title"] in existing:
            skipped += 1
            continue
        if dry_run:
            seeded += 1
            continue
        try:
            created = create_sop(
                title=sop["title"],
                category=sop["category"],
                description=sop["description"],
                steps=sop["steps"],
                prerequisites=sop.get("prerequisites"),
                validation=sop.get("validation"),
                rollback=sop.get("rollback"),
                escalation=sop.get("escalation"),
                author="seed_sops",
                classification=sop.get("classification", "CUI"),
                csp=sop.get("csp", "multi"),
            )
            sop_id = created["sop_id"]

            if status in ("review", "approved"):
                submit_for_review(sop_id, reviewer="ndc-admin", submitted_by="seed_sops")
            if status == "approved":
                approve_sop(sop_id, approver="ndc-admin", comment="Auto-approved by seed_sops")

            seeded += 1
        except Exception as exc:  # noqa: BLE001
            errors.append({"title": sop["title"], "error": str(exc)})

    return {"seeded": seeded, "skipped": skipped, "errors": errors, "total": len(ALL_SOPS)}


