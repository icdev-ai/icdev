_VALIDATION_SCRIPT = '''\
#!/usr/bin/env python3
"""QDC Quality Infrastructure Validation Script — Generated by ICDEV™
Generated: {ts}

Run after `terraform apply` to verify all resources are provisioned.
Usage:
  pip install boto3
  python validate_{uid}.py --region us-gov-west-1 [--profile <aws-profile>]
"""
import argparse
import sys
import boto3


def check(label, ok, detail=""):
    status = "PASS" if ok else "FAIL"
    msg = "  [" + status + "] " + str(label)
    if detail:
        msg += " -- " + str(detail)
    print(msg)
    return ok


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--region", default="us-gov-west-1")
    parser.add_argument("--profile", default=None)
    args = parser.parse_args()

    session = boto3.Session(region_name=args.region, profile_name=args.profile)
    passed = failed = 0
    print("\\n=== QDC Quality Infrastructure Validation ===\\n")

    # CodeBuild project
    try:
        cb = session.client("codebuild")
        projects = cb.batch_get_projects(names=["{env}-qdc-quality-gate"])["projects"]
        ok = check("CodeBuild quality-gate project", bool(projects))
    except Exception as e:
        ok = check("CodeBuild quality-gate project", False, str(e))
    passed += ok; failed += not ok

    # S3 quality reports bucket
    try:
        s3 = session.client("s3")
        sts = session.client("sts")
        account_id = sts.get_caller_identity()["Account"]
        bucket = f"{{args.region}}-qdc-quality-reports-{{account_id}}"
        s3.head_bucket(Bucket=bucket)
        ok = check("S3 quality-reports bucket", True, bucket)
    except Exception as e:
        ok = check("S3 quality-reports bucket", False, str(e))
    passed += ok; failed += not ok

    # CloudWatch alarm
    try:
        cw = session.client("cloudwatch")
        alarms = cw.describe_alarms(AlarmNames=["{env}-qdc-quality-score-low"])["MetricAlarms"]
        ok = check("CloudWatch quality-score-low alarm", bool(alarms))
    except Exception as e:
        ok = check("CloudWatch quality-score-low alarm", False, str(e))
    passed += ok; failed += not ok

    # SNS topic
    try:
        sns = session.client("sns")
        topics = sns.list_topics()["Topics"]
        found = any("{env}-qdc-quality-alerts" in t["TopicArn"] for t in topics)
        ok = check("SNS quality-alerts topic", found)
    except Exception as e:
        ok = check("SNS quality-alerts topic", False, str(e))
    passed += ok; failed += not ok

    # SSM parameter
    try:
        ssm = session.client("ssm")
        ssm.get_parameter(Name="/qdc/sonar_token", WithDecryption=False)
        ok = check("SSM sonar_token parameter", True)
    except Exception as e:
        ok = check("SSM sonar_token parameter", False, str(e))
    passed += ok; failed += not ok

    print("\\n=== Result: " + str(passed) + " passed, " + str(failed) + " failed ===\\n")
    sys.exit(0 if failed == 0 else 1)


if __name__ == "__main__":
    main()
'''

