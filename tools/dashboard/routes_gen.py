#!/usr/bin/env python3
# CUI // SP-CTI
"""The dashboard's route table, generated from the live Flask url_map (icx-cnf-08).

    python tools/dashboard/routes_gen.py            write tools/dashboard/static/js/routes.gen.js
    python tools/dashboard/routes_gen.py --check    exit 1 when the file is not what the url_map generates

Every url_map endpoint is mapped to its rules and methods. A page calls a route by
its endpoint id, never by a path it writes itself:

    icdevFetch('ace_api.api_launch', {}, {method: 'POST', body: ...})
    icdevRoute('ace.instance_detail', {instance_id: id})

The helpers fill the rule, encode each parameter, and refuse a missing, empty or
unknown parameter, an unknown endpoint, or a method the rule does not serve,
before anything is sent. So the feature-conformance audit
(tools/conformance/feature_audit.py) reads exactly which routes a page calls. In
Jinja, ``url_for('<endpoint>')`` is the same thing on the server side.

The table comes from the same scrubbed url_map probe the audit judges
(``feature_audit.probe_rules``), so the two cannot disagree. The audit's
``--check``, and with it the ``feature_conformance`` coherence check, fails when
this file is stale.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Iterable, Optional

# sys.path BOOTSTRAP (the import root, not a data path).
_BOOTSTRAP_ROOT = Path(__file__).resolve().parents[2]
if str(_BOOTSTRAP_ROOT) not in sys.path:
    sys.path.insert(0, str(_BOOTSTRAP_ROOT))

from icdev.core.paths import repo_root  # noqa: E402

BASE_DIR = repo_root(__file__)
OUT_RELPATH = "tools/dashboard/static/js/routes.gen.js"
_SKIP_METHODS = frozenset({"HEAD", "OPTIONS"})

HEAD = """\
/* CUI // SP-CTI
 * GENERATED by tools/dashboard/routes_gen.py from the live Flask url_map (icx-cnf-08).
 * Do not edit: run  python tools/dashboard/routes_gen.py
 *
 * A page calls a route by its endpoint id here, never by a path it writes itself:
 *   icdevFetch('ace_api.api_launch', {}, {method: 'POST', body: ...})
 *   icdevRoute('ace.instance_detail', {instance_id: id})
 * Loaded by base.html in <head>, before any page script.
 */
(function () {
  'use strict';
"""

TAIL = r"""
  var PARAM = /<(?:([a-zA-Z_][\w]*)(?:\([^)]*\))?:)?([a-zA-Z_]\w*)>/g;

  function names(rule) {
    var out = [];
    rule.replace(PARAM, function (_m, _conv, name) { out.push(name); return ''; });
    return out.sort();
  }

  function pick(endpoint, params) {
    var rules = ROUTES[endpoint];
    if (!rules) { throw new Error('icdevRoute: unknown endpoint ' + endpoint); }
    var given = Object.keys(params).sort();
    for (var i = 0; i < rules.length; i++) {
      if (names(rules[i][0]).join(',') === given.join(',')) { return rules[i]; }
    }
    var want = rules.map(function (r) { return '{' + names(r[0]).join(', ') + '}'; });
    throw new Error('icdevRoute: ' + endpoint + ' takes ' + want.join(' or ') +
                    ', not {' + given.join(', ') + '}');
  }

  /** Fill an endpoint's rule. Every <param> is required and never empty; a param the
   *  rule does not take is refused. `query` is appended (null/undefined left out). */
  function icdevRoute(endpoint, params, query) {
    params = params || {};
    var rule = pick(endpoint, params)[0];
    var path = rule.replace(PARAM, function (_m, conv, name) {
      var v = params[name];
      if (v === undefined || v === null || v === '') {
        throw new Error('icdevRoute: ' + endpoint + ' needs ' + name);
      }
      var s = String(v);
      return conv === 'path' ? s.split('/').map(encodeURIComponent).join('/') : encodeURIComponent(s);
    });
    if (query) {
      var qs = (query instanceof URLSearchParams) ? query.toString() : Object.keys(query)
        .filter(function (k) { return query[k] !== undefined && query[k] !== null; })
        .map(function (k) { return encodeURIComponent(k) + '=' + encodeURIComponent(String(query[k])); })
        .join('&');
      if (qs) { path += '?' + qs; }
    }
    return path;
  }

  /** fetch() a route by its endpoint id. The method (default GET) must be one the rule serves. */
  function icdevFetch(endpoint, params, init, query) {
    init = init || {};
    var method = String(init.method || 'GET').toUpperCase();
    var picked = pick(endpoint, params || {});
    if (picked[1].indexOf(method) < 0) {
      return Promise.reject(new Error('icdevFetch: ' + endpoint + ' serves ' +
                                      picked[1].join('/') + ', not ' + method));
    }
    var url;
    try { url = icdevRoute(endpoint, params, query); } catch (e) { return Promise.reject(e); }
    return fetch(url, init);
  }

  window.ICDEV_ROUTES = ROUTES;
  window.icdevRoute = icdevRoute;
  window.icdevFetch = icdevFetch;
})();
"""


def table(rules: Iterable[dict[str, Any]]) -> dict[str, list[list[Any]]]:
    """endpoint -> [[rule, [methods]], ...], sorted; ``static`` endpoints left out."""
    out: dict[str, dict[str, set[str]]] = {}
    for r in rules:
        endpoint = str(r["endpoint"])
        if endpoint == "static" or endpoint.endswith(".static"):
            continue
        methods = set(r.get("methods") or []) - _SKIP_METHODS
        out.setdefault(endpoint, {}).setdefault(str(r["rule"]), set()).update(methods)
    return {ep: [[rule, sorted(m)] for rule, m in sorted(by_rule.items())]
            for ep, by_rule in sorted(out.items())}


def render(rules: Iterable[dict[str, Any]]) -> str:
    rows = table(rules)
    body = "".join(f"    {json.dumps(ep)}: {json.dumps(r, separators=(',', ':'))},\n"
                   for ep, r in rows.items())
    return HEAD + "  var ROUTES = {\n" + body + "  };\n" + TAIL


_ROW_RE = None


def load_table(root: Optional[Path] = None) -> dict[str, list[list[Any]]]:
    """The committed table, read back: endpoint -> [[rule, [methods]], ...]."""
    import re

    global _ROW_RE
    _ROW_RE = _ROW_RE or re.compile(r'^    ("[^"]+"): (\[.*\]),$')
    out = {}
    path = (root or BASE_DIR) / OUT_RELPATH
    for line in path.read_text(encoding="utf-8").splitlines():
        m = _ROW_RE.match(line)
        if m:
            out[json.loads(m.group(1))] = json.loads(m.group(2))
    return out


def rule_of(endpoint: str, root: Optional[Path] = None) -> str:
    """The one rule of *endpoint* (KeyError if unknown, ValueError if it has several)."""
    rules = load_table(root)[endpoint]
    if len(rules) != 1:
        raise ValueError(f"{endpoint} has {len(rules)} rules")
    return rules[0][0]


def current(rules: Iterable[dict[str, Any]], root: Optional[Path] = None) -> bool:
    path = (root or BASE_DIR) / OUT_RELPATH
    return path.is_file() and path.read_text(encoding="utf-8") == render(rules)


def write(rules: Iterable[dict[str, Any]], root: Optional[Path] = None) -> Path:
    path = (root or BASE_DIR) / OUT_RELPATH
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(rules), encoding="utf-8")
    return path


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help=f"exit 1 when {OUT_RELPATH} is stale")
    parser.add_argument("--json", action="store_true", help="JSON output (the default)")
    args = parser.parse_args(argv)
    from tools.conformance.feature_audit import AuditError, probe_rules

    try:
        rules = probe_rules(BASE_DIR)
    except AuditError as exc:
        print(json.dumps({"ok": False, "error": str(exc)}), file=sys.stderr)
        return 2
    if args.check:
        ok = current(rules)
        print(json.dumps({"current": ok, "file": OUT_RELPATH}))
        return 0 if ok else 1
    write(rules)
    print(json.dumps({"written": OUT_RELPATH, "endpoints": len(table(rules))}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
