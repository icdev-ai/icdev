# CUI // SP-CTI
"""The cloud-native target of one legacy application, generated from static analysis (ICDEV[OS] osx-fth-14).

ICDEV[OS]'s modernisation samples plan each application to a cloud-native end state -- containerised, twelve-factor
configuration, a managed database, events in place of message-driven beans -- and no tool reached any of it. This module
READS the application's source (never builds or runs it: the source is untrusted data) and generates, as CAM jobs:

    container_definition    Containerfile (an OCI build file) and deployment.yaml (a minimal Deployment and Service)
                            from the stack it read: language and level, build tool, packaging, ports, config files
    config_externalisation  config-findings.json: every setting found hard-coded (JDBC URLs, connection strings,
                            credentials, hostnames, URLs, file paths, ports) by WHERE it is, never its value;
                            env.mapping.json and config.env.example: the environment variables that replace them
    twelve_factor_report    twelve-factor.json: each of the twelve factors met, not_met or UNVERIFIED, from evidence;
                            unverified wherever static analysis cannot tell, never met on nothing found
    event_contract          asyncapi.yaml and event-contract.json: each message-driven bean's destination as a channel,
                            the commands it dispatches on as messages, their payload from what producers set

Everything written is GENERATED and UNREVIEWED: ICDEV[IT]'s exporter binds each file by its SHA-256 and ICDEV[OS]
shows it so. A credential's value is never read into a finding, a report or a generated file. ``targets`` maps the
plan's declared target (ICDEV[OS] examples/modernisation/apps.yaml) to what proposes each item; nothing here says a
target is reached -- only running the application could show that.

The CAM engine runs these (``cam_refactor_engine._run_code_scaffold``); ``cloud_native_jobs.py`` queues them.
"""
from __future__ import annotations

import functools
import json
import re
from pathlib import Path

import yaml

TOOL = "icdev-it/cloud_native"
FACTORS = ("codebase", "dependencies", "config", "backing_services", "build_release_run", "processes", "port_binding",
           "concurrency", "disposability", "dev_prod_parity", "logs", "admin_processes")
#: The current level a language moves to (the version migrator's target: context/migration/refactor_rules.yaml).
TARGET_LEVEL = {"java": "17", "csharp": "8.0"}
SCAFFOLDS = ("container_definition", "config_externalisation", "twelve_factor_report", "event_contract")
HEADER = ("GENERATED by ICDEV[IT] cloud_native (ICDEV[OS] osx-fth-14) from static analysis of the source, which was "
          "never built or run. UNREVIEWED: a person reviews it before anything uses it.")

_SKIP_DIRS = {".git", ".svn", "target", "build", "bin", "obj", "node_modules", "packages", ".idea", ".vs", "dist"}
_TEXT = {".java", ".xml", ".properties", ".yaml", ".yml", ".json", ".config", ".cs", ".jsp", ".env", ".conf", ".ini",
         ".gradle", ".kts", ".csproj", ".cshtml", ".sql", ".txt", ".md", ".xmi"}
_MAX_BYTES = 1_000_000
_MAX_FINDINGS = 300
_CI = (".github/", ".travis.yml", ".gitlab-ci.yml", "azure-pipelines", "Jenkinsfile", ".circleci/")
#: what does not run with the application: tests, documentation sites, the build wrapper
_NOT_RUNTIME = re.compile(r"(?i)(^|/)(src/test|test|tests|it|src/site|site|docs?|\.mvn)/|(Tests?|IT)\.(java|cs)$|"
                          r"(^|/)[\w.]*\.Tests?/")


# --- reading the source (text only; nothing is executed) ------------------------------------------------------------

def _files(root: Path) -> list[str]:
    out = []
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if any(part in _SKIP_DIRS for part in rel.parts[:-1]) or not p.is_file() or p.is_symlink():
            continue
        out.append(rel.as_posix())
    return out


def _text(root: Path, rel: str) -> str | None:
    p = root / rel
    if p.suffix.lower() not in _TEXT and p.name not in ("Dockerfile", "Containerfile", "mvnw", "Procfile") \
            and not p.name.startswith("Dockerfile"):
        return None
    try:
        if p.stat().st_size > _MAX_BYTES:
            return None
        return p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None


def _is_ci(rel: str) -> bool:
    return any(rel.startswith(c) or rel == c for c in _CI)


def _is_manifest(text: str) -> str | None:
    m = re.search(r"(?m)^kind:\s*(Deployment|Service|StatefulSet|Secret|ConfigMap|Pod|Job|DaemonSet|Route|Ingress)\b", text)
    return m.group(1) if m else None


_CONFIG_NAMES = re.compile(r"(?i)(^|/)(server\.xml|web\.xml|persistence\.xml|ejb-jar\.xml|ibm-[\w-]+\.xml|"
                           r"applicationcontext[\w-]*\.xml|[\w.-]*\.properties|[\w.-]*\.config|appsettings[\w.-]*\.json|"
                           r"application[\w-]*\.ya?ml|bootstrap\.properties|server\.env|[\w.-]*\.env|log4j[\w.-]*|"
                           r"logback[\w.-]*\.xml|jboss-[\w-]+\.xml|context\.xml)$")


def _env_name(*parts: str) -> str:
    s = "_".join(p for p in parts if p)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper()
    return ("CFG_" + s) if not s or s[0].isdigit() else s


def _placeholder(v: str) -> bool:
    v = v.strip()
    return not v or v.startswith(("${", "#{", "$(", "%", "{{")) or v in ("*", "changeit?")


_SECRETY = re.compile(r"(?i)(password|passwd|pwd|secret|api[_-]?key|token|credential)$")
_USERY = re.compile(r"(?i)^(user|username|user_?name|userid|user_?id|uid|login)$")
_XML_ATTR = re.compile(r'([A-Za-z_][\w.:-]*)\s*=\s*"([^"]*)"')
_PROP = re.compile(r"^\s*([A-Za-z_][\w.\-]*)\s*[=:]\s*(.*?)\s*$")
_JDBC = re.compile(r"jdbc:[a-z0-9]+:[^\s\"'<>]*")
_HOST = re.compile(r"(?<![\w.])(localhost|127\.0\.0\.1|(?:\d{1,3}\.){3}\d{1,3})(?![\w.])")
_URL = re.compile(r"\bhttps?://([A-Za-z0-9.\-]+)(?::\d+)?[^\s\"'<>]*")
_ABS = re.compile(r"(?<![\w/:.])(/(?:opt|var|usr|etc|home|tmp|data|srv|mnt)/[\w./\-]+|[A-Za-z]:\\\\?[\w\\. \-]+)")
_PORT_ATTR = re.compile(r'(?i)\b(httpPort|httpsPort|port|iiopPort|iiopsPort)\s*=\s*"(\d{2,5})"')
#: hosts that name a schema or a namespace, never a backing service
_SCHEMA_HOSTS = re.compile(r"(?i)(w3\.org|java\.sun\.com|jcp\.org|springframework\.org|mybatis\.org|schemas\.microsoft|"
                           r"maven\.apache\.org|jakarta\.ee|hibernate\.org|apache\.org/dtds|ibm\.com/xml|"
                           r"websphere\.ibm\.com|oracle\.com/webfolder|xmlns|stripes|openliberty\.io|"
                           r"go\.microsoft\.com|aka\.ms|github\.com|apache\.org/licenses)")


def _attr_context(line: str) -> str:
    m = re.search(r'\b(?:id|name)\s*=\s*"([^"]+)"', line)
    if m:
        return m.group(1)
    t = re.search(r"<\s*([A-Za-z_][\w.:-]*)", line)
    return t.group(1).split(":")[-1].split(".")[-1] if t else ""


def _config_findings(root: Path, files: list[str], texts: dict[str, str]) -> tuple[list[dict], int]:
    """Every hard-coded setting found, by location (``path:line``) and kind, NEVER its value."""
    out: dict[tuple, dict] = {}

    def add(kind, rel, ln, key, literal, env):
        k = (kind, rel, ln, key)
        if k not in out:
            out[k] = {"kind": kind, "location": f"{rel}:{ln}", "key": key or None, "literal": bool(literal), "env": env}

    for rel in files:
        text = texts.get(rel)
        if text is None or _is_ci(rel) or rel.endswith(("pom.xml", ".csproj", ".sln", ".md", ".txt", ".sql", ".xmi")):
            continue
        is_cfg = bool(_CONFIG_NAMES.search(rel)) or _is_manifest(text) is not None
        is_code = rel.endswith((".java", ".cs", ".jsp", ".cshtml"))
        manifest = _is_manifest(text)
        in_data = False
        for ln, line in enumerate(text.splitlines(), 1):
            if "xmlns" in line or "schemaLocation" in line or "<!DOCTYPE" in line:
                continue
            for m in _JDBC.finditer(line):
                ctx = _attr_context(line) if rel.endswith(".xml") else (_PROP.match(line) or [None, ""])[1]
                add("jdbc_url", rel, ln, ctx or None, True, _env_name(ctx) if ctx else "JDBC_URL")
            if is_cfg and re.search(r"(?i)connectionString\s*[=:]", line):
                ctx = _attr_context(line)
                add("connection_string", rel, ln, ctx or None, True, _env_name("connection_string", ctx))
                if re.search(r"(?i)(password|pwd)\s*=", line):
                    add("credential", rel, ln, f"{ctx}.password" if ctx else "password", True,
                        _env_name(ctx, "password"))
            if manifest == "Secret":                     # a Secret manifest's data keys, never their values
                if re.match(r"^(data|stringData):\s*$", line):
                    in_data = True
                elif in_data and re.match(r"^\s+[\w.-]+:\s*\S", line):
                    key = line.strip().split(":", 1)[0]
                    add("credential", rel, ln, key, True, _env_name(key))
                elif line and not line[0].isspace():
                    in_data = False
            if is_cfg and rel.endswith((".xml", ".config")):
                ctx = _attr_context(line)
                for a, v in _XML_ATTR.findall(line):
                    name = a.split(":")[-1]
                    if _SECRETY.search(name) or _USERY.match(name):
                        add("credential", rel, ln, f"{ctx}.{name}" if ctx else name, not _placeholder(v),
                            _env_name(ctx, name))
                    elif name.lower() in ("host", "hostname", "servername", "server") and v not in ("*", ""):
                        add("hostname", rel, ln, f"{ctx}.{name}" if ctx else name, not _placeholder(v),
                            _env_name(ctx, name))
                    elif name.lower() in ("databasename", "logdirectory", "location", "path", "dir", "directory") \
                            and ("/" in v or "\\" in v) and not v.startswith(("classpath:", "res://")):
                        add("file_path", rel, ln, f"{ctx}.{name}" if ctx else name, not _placeholder(v),
                            _env_name(ctx, name))
                for a, _v in _PORT_ATTR.findall(line):
                    add("port", rel, ln, f"{ctx}.{a}" if ctx else a, True, _env_name(ctx, a))
            elif is_cfg and rel.endswith((".properties", ".env", ".ini", ".conf", ".yaml", ".yml")) and manifest is None:
                m = _PROP.match(line)
                if m and not line.lstrip().startswith(("#", "!")):
                    k, v = m.group(1), m.group(2)
                    if _SECRETY.search(k) or _USERY.match(k.split(".")[-1]):
                        add("credential", rel, ln, k, not _placeholder(v), _env_name(k))
                    elif re.search(r"(?i)(^|\.)(port)$", k) and v.strip().isdigit():
                        add("port", rel, ln, k, True, _env_name(k))
                    elif re.search(r"(?i)(host|server)$", k) and v.strip():
                        add("hostname", rel, ln, k, not _placeholder(v), _env_name(k))
                    elif (v.startswith("/") or re.match(r"[A-Za-z]:\\", v)) and len(v) > 1:
                        add("file_path", rel, ln, k, True, _env_name(k))
            if is_code:
                for m in re.finditer(r'(?i)\b\w*?(password|passwd|pwd|secret)\s*=\s*"([^"]+)"', line):
                    add("credential", rel, ln, m.group(1), True, _env_name(Path(rel).stem, m.group(1)))
            for m in _HOST.finditer(line if not re.search(r"(?i)version", line) else ""):   # 1.0.0.0 is a version
                if is_cfg or (is_code and re.search(r'"[^"]*' + re.escape(m.group(1)), line)):
                    add("hostname", rel, ln, None, True, "SERVICE_HOST")
            if is_cfg:
                for m in _URL.finditer(line):
                    if _SCHEMA_HOSTS.search(m.group(0)) or _HOST.fullmatch(m.group(1) or ""):
                        continue
                    add("url", rel, ln, _attr_context(line) or None, True, _env_name(_attr_context(line), "url"))
                if not rel.endswith((".xml", ".config")):
                    for m in _ABS.finditer(line):
                        if not any(k[0] == "file_path" and k[1:3] == (rel, ln) for k in out):
                            add("file_path", rel, ln, None, True, "DATA_DIR")
    rows = sorted(out.values(), key=lambda f: (f["location"].rsplit(":", 1)[0], int(f["location"].rsplit(":", 1)[1]),
                                              f["kind"], f["key"] or ""))
    return rows[:_MAX_FINDINGS], len(rows)


def env_mapping(findings: list[dict]) -> list[dict]:
    """The environment variables that replace the findings: one per name, secret when any credential maps to it."""
    by: dict[str, dict] = {}
    for f in findings:
        if not f.get("env"):
            continue
        e = by.setdefault(f["env"], {"name": f["env"], "secret": False, "locations": []})
        e["secret"] = e["secret"] or f["kind"] == "credential"
        if f["location"] not in e["locations"]:
            e["locations"].append(f["location"])
    return [by[k] for k in sorted(by)]


# --- the stack -----------------------------------------------------------------------------------------------------

def _first(texts: dict[str, str], pred) -> list[str]:
    return [r for r in sorted(texts) if pred(r)]


@functools.lru_cache(maxsize=8)
def _analyse(source: str, language: str, version: str, framework: str) -> dict:
    root = Path(source)
    files = _files(root)
    texts = {r: t for r in files if not _NOT_RUNTIME.search(r) and (t := _text(root, r)) is not None}
    lang = (language or "").lower()
    fw = (framework or "").strip().lower()
    poms = [r for r in files if r.endswith("pom.xml")]
    gradles = [r for r in files if r.endswith(("build.gradle", "build.gradle.kts"))]
    csprojs = [r for r in files if r.endswith(".csproj")]
    build_tool = "maven" if poms else "gradle" if gradles else "msbuild" if csprojs else None
    if build_tool == "maven" and any(r in ("mvnw", "mvnw.cmd") for r in files):
        build_tool = "maven (wrapper)"
    packs = [m.group(1) for r in poms for m in [re.search(r"<packaging>\s*(\w+)\s*</packaging>", texts.get(r, ""))] if m]
    web_config = [r for r in files if r.lower().endswith("web.config")]
    packaging = ("ear" if "ear" in packs else "war" if "war" in packs else "jar" if packs or gradles else
                 "ASP.NET web application (IIS)" if web_config else None)
    liberty = [r for r in files if r.endswith("server.xml") and "<featureManager" in texts.get(r, "")]
    boot = any("spring-boot" in texts.get(r, "") for r in poms + gradles)
    cfg_files = sorted(r for r in files if _CONFIG_NAMES.search(r) and not _is_ci(r)
                       and not (texts.get(r) and _is_manifest(texts[r])))
    container_files = sorted(r for r in files if Path(r).name.startswith(("Dockerfile", "Containerfile"))
                             or re.search(r"(^|/)(docker-)?compose[\w.-]*\.ya?ml$", r) or Path(r).name == "Chart.yaml"
                             or (r.endswith((".yaml", ".yml")) and not _is_ci(r) and texts.get(r) and _is_manifest(texts[r])))
    ports: dict[int, dict] = {}
    for r in liberty + [x for x in cfg_files if x.endswith((".properties", ".yml", ".yaml"))] + \
            [x for x in container_files if Path(x).name.startswith(("Dockerfile", "Containerfile"))]:
        for ln, line in enumerate(texts.get(r, "").splitlines(), 1):
            for m in re.finditer(r'(?i)\bhttps?Port\s*=\s*"(\d{2,5})"', line):
                ports.setdefault(int(m.group(1)), {"port": int(m.group(1)), "found": True, "location": f"{r}:{ln}"})
            m = re.match(r"\s*server\.port\s*[=:]\s*(\d{2,5})\s*$", line)
            if m:
                ports.setdefault(int(m.group(1)), {"port": int(m.group(1)), "found": True, "location": f"{r}:{ln}"})
            m = re.match(r"(?i)\s*EXPOSE\s+([\d\s/a-z]+)$", line)
            if m:
                for p in re.findall(r"\d{2,5}", m.group(1)):
                    ports.setdefault(int(p), {"port": int(p), "found": True, "location": f"{r}:{ln}"})
    target = TARGET_LEVEL.get(lang)
    if lang == "java":
        runtime = (f"Java {target} on a Jakarta EE application server" if fw == "ejb" or packaging == "ear" or liberty
                   else f"Java {target} (self-contained Spring Boot)" if boot else f"Java {target} servlet container")
        default_port = 9080 if (fw == "ejb" or liberty) else 8080
    elif lang == "csharp":
        runtime, default_port = f".NET {target.split('.')[0] if target else ''} ASP.NET Core (Kestrel)".replace("  ", " "), 8080
    else:
        runtime, default_port = None, None
    if not ports and default_port:
        ports[default_port] = {"port": default_port, "found": False, "location": None}
    findings, total = _config_findings(root, files, texts)
    return {"root": str(root), "files": files, "texts": texts,
            "stack": {"language": lang or None, "version": version or None, "framework": fw or None,
                      "build_tool": build_tool, "packaging": packaging, "runtime": runtime,
                      "ports": [ports[p] for p in sorted(ports)], "config_files": cfg_files,
                      "container_files": container_files},
            "poms": poms, "gradles": gradles, "csprojs": csprojs, "boot": boot, "liberty": liberty,
            "web_config": web_config, "findings": findings, "findings_total": total}


def analyse(source: str | Path, *, language: str = "", version: str = "", framework: str = "") -> dict:
    """What the source is, read statically: its stack and the configuration found hard-coded in it."""
    return _analyse(str(Path(source).resolve()), language or "", version or "", framework or "")


# --- the twelve factors --------------------------------------------------------------------------------------------

def _grep(a: dict, pattern: str, suffixes: tuple[str, ...], limit: int = 5) -> list[str]:
    rx, hits = re.compile(pattern), []
    for r in sorted(a["texts"]):
        if not r.endswith(suffixes) or _is_ci(r):
            continue
        for ln, line in enumerate(a["texts"][r].splitlines(), 1):
            if rx.search(line):
                hits.append(f"{r}:{ln}")
                break
        if len(hits) >= limit:
            break
    return hits


def _count(a: dict, pattern: str, suffixes: tuple[str, ...]) -> int:
    rx = re.compile(pattern)
    return sum(1 for r, t in a["texts"].items() if r.endswith(suffixes) and not _is_ci(r) and rx.search(t))


def twelve_factor(a: dict) -> list[dict]:
    """Each factor from what was read. ``met`` and ``not_met`` name their evidence; ``unverified`` says why static
    analysis cannot tell. Absence of a finding is never ``met``."""
    st, f = a["stack"], {}
    code = (".java", ".cs", ".jsp", ".cshtml")
    xmlcfg = (".xml", ".config", ".properties", ".yaml", ".yml", ".json")

    f["codebase"] = ("unverified", ("one source tree was analysed; whether it is one codebase in revision control, "
                     "deployed many times, is not visible in a source tree"), ["1 source tree"])
    manifests = a["poms"] + a["gradles"] + a["csprojs"] + [r for r in a["files"] if r.endswith("packages.config")]
    vendored = [r for r in a["files"] if r.endswith((".jar", ".dll")) and "/lib/" in f"/{r}"]
    if vendored:
        f["dependencies"] = ("not_met", f"{len(vendored)} library file(s) are vendored in the source tree", vendored[:5])
    elif manifests:
        f["dependencies"] = ("met", f"declared in {len(manifests)} build or package file(s)", manifests[:5])
    else:
        f["dependencies"] = ("unverified", "no build or package file was found", [])
    lit = [x for x in a["findings"] if x["literal"] and x["kind"] != "port"]
    if lit:
        kinds = sorted({x["kind"] for x in lit})
        f["config"] = ("not_met", (f"{len(lit)} setting(s) written into the source ({', '.join(kinds)}); "
                                  "config-findings.json lists where"), [x["location"] for x in lit[:8]])
    else:
        f["config"] = ("unverified", ("no hard-coded setting was found by the patterns read; that does not show all "
                                     "configuration comes from the environment"), [])
    embedded = _grep(a, r"(?i)(derby\.embedded|DerbyEmbedded|jdbc:derby:(?!//)|jdbc:hsqldb:mem|jdbc:h2:mem|"
                        r"embedded-database|AttachDbFilename|\(LocalDB\)|\.mdf\b)", xmlcfg + code)
    jdbc_lit = [x["location"] for x in a["findings"] if x["kind"] in ("jdbc_url", "connection_string")]
    jndi = _grep(a, r"(jndiName\s*=|@Resource\s*\(\s*(lookup|name|mappedName)|InitialContext|lookup\(\s*\"java:)", xmlcfg + code)
    if embedded:
        f["backing_services"] = ("not_met", "the database is embedded in the application, not an attached resource",
                                 embedded)
    elif jdbc_lit:
        f["backing_services"] = ("not_met", "a database location is written into the source", jdbc_lit[:5])
    elif jndi:
        f["backing_services"] = ("unverified", ("resources are looked up by name (JNDI); where they are bound is the "
                                               "server's configuration, not visible here"), jndi)
    else:
        f["backing_services"] = ("unverified", "no backing-service configuration was found", [])
    ci = sorted({r.split("/")[0] + "/" if r.startswith(".github/") else r for r in a["files"] if _is_ci(r)})
    f["build_release_run"] = ("unverified", "the build is declared"
                              + (f" ({st['build_tool']})" if st["build_tool"] else " nowhere found")
                              + "; whether release and run are separate stages is not visible in source",
                              manifests[:2] + ci[:3])
    sess = _grep(a, r"(HttpSession\b|getSession\s*\(|@Stateful\b|\bSession\s*\[|HttpContext\.Current\.Session|"
                    r"<stateful-session|session-type>Stateful)", code + (".xml",))
    if sess:
        n = _count(a, r"(HttpSession|getSession|@Stateful|Session\[)", code)
        f["processes"] = ("not_met", f"server-side session state is kept ({n} file(s)): a process is not stateless", sess)
    else:
        f["processes"] = ("unverified", ("no session state was found by the patterns read; statelessness is not shown "
                                        "by its absence"), [])
    if st["packaging"] in ("war", "ear"):
        f["port_binding"] = ("not_met", (f"deployed into an application server as a {st['packaging']}, not "
                                        "self-contained"), a["poms"][:3])
    elif a["web_config"]:
        f["port_binding"] = ("not_met", "hosted by IIS (Web.config), not self-contained", a["web_config"][:3])
    elif a["boot"]:
        f["port_binding"] = ("met", "a self-contained Spring Boot application binds its own port", a["poms"][:3] or a["gradles"][:3])
    else:
        f["port_binding"] = ("unverified", "how the application is hosted is not visible", [])
    f["concurrency"] = ("unverified", ("scaling by running more processes depends on how it runs, which static analysis "
                                      "does not see"), [])
    f["disposability"] = ("unverified", "start-up time and graceful shutdown are seen running, not in source",
                          _grep(a, r"(@Startup\b|ServletContextListener|contextInitialized|Application_Start)", code))
    parity = _grep(a, r"(?i)(derby|hsqldb|jdbc:h2:|LocalDB)", xmlcfg)
    transforms = [r for r in a["files"] if re.search(r"(?i)web\.(debug|release)\.config$|application-(dev|prod)\.", r)]
    if parity or transforms:
        f["dev_prod_parity"] = ("not_met", ("a development database ships with the application"
                                            if parity else "configuration differs by environment") +
                                (" and configuration differs by environment" if parity and transforms else ""),
                                (parity + transforms)[:5])
    else:
        f["dev_prod_parity"] = ("unverified", "no difference between environments was found in source", [])
    filelog = _grep(a, r"(?i)(FileAppender|RollingFile|logDirectory|<file>|FileHandler|log4net.*File|"
                       r"new\s+FileWriter\([^)]*log)", xmlcfg + code)
    if filelog:
        f["logs"] = ("not_met", "logs are written to files the application manages", filelog)
    else:
        f["logs"] = ("unverified", "no log file was found configured; writing to stdout is seen running",
                     _grep(a, r"(System\.out\.print|Console\.Write|Trace\.Write)", code, 3))
    initdb = _grep(a, r"(?i)(jdbc:script|createDatabase\s*=\s*\"create\"|buildDB|resetTrade|initialize-database|"
                      r"Database\.SetInitializer|hibernate\.hbm2ddl\.auto)", xmlcfg + code)
    if initdb:
        f["admin_processes"] = ("not_met", ("the schema or data is set up by the running application, not by a one-off "
                                           "admin process"), initdb)
    else:
        f["admin_processes"] = ("unverified", "no admin task was found; one-off processes are seen running", [])
    return [{"id": k, "status": f[k][0], "why": f[k][1], "evidence": list(f[k][2])} for k in FACTORS]


# --- events in place of message-driven beans ------------------------------------------------------------------------

_JMS_TYPES = {"String": "string", "Int": "integer", "Long": "integer", "Short": "integer", "Byte": "integer",
              "Double": "number", "Float": "number", "Boolean": "boolean", "Object": "object"}


def events(a: dict) -> list[dict]:
    """Each message-driven bean's destination as a channel; the commands it dispatches on as messages; each message's
    payload from what its producers set (else from what the bean reads)."""
    beans = []
    for r, t in sorted(a["texts"].items()):
        if not r.endswith(".java") or "@MessageDriven" not in t:
            continue
        dest = re.search(r'propertyName\s*=\s*"destination"\s*,\s*propertyValue\s*=\s*"([^"]+)"', t)
        dtype = re.search(r'propertyName\s*=\s*"destinationType"\s*,\s*propertyValue\s*=\s*"([^"]+)"', t)
        mapped = re.search(r'mappedName\s*=\s*"([^"]+)"', t)
        cls = re.search(r"\bclass\s+(\w+)", t)
        d = (dest or mapped)
        cmds = sorted(set(re.findall(r'command\s*\.\s*equals(?:IgnoreCase)?\s*\(\s*"([^"]+)"\s*\)', t)))
        reads = {n: _JMS_TYPES.get(ty, "string") for ty, n in re.findall(r'\.get(\w+?)Property\s*\(\s*"([^"]+)"', t)}
        beans.append({"file": r, "class": cls.group(1) if cls else Path(r).stem, "destination": d.group(1) if d else None,
                      "kind": "topic" if dtype and "topic" in dtype.group(1).lower() else "queue",
                      "commands": cmds, "reads": reads})
    if not beans:
        return []
    produced: dict[str, dict] = {}
    for r, t in sorted(a["texts"].items()):
        if not r.endswith(".java") or "Property(\"command\"" not in t:
            continue
        lines = t.splitlines()
        for i, line in enumerate(lines):
            m = re.search(r'\.set\w*Property\s*\(\s*"command"\s*,\s*"([^"]+)"', line)
            if not m:
                continue
            fields = {}
            for nxt in lines[i + 1:i + 40]:
                if re.search(r"\.send\s*\(", nxt):
                    break
                for ty, n in re.findall(r'\.set(\w+?)Property\s*\(\s*"([^"]+)"', nxt):
                    fields[n] = _JMS_TYPES.get(ty, "string")
            e = produced.setdefault(m.group(1).lower(), {"fields": {}, "producers": []})
            e["fields"].update(fields)
            e["producers"].append(f"{r}:{i + 1}")
    out = []
    for b in beans:
        if not b["destination"]:
            continue
        msgs = []
        for c in b["commands"] or ["message"]:
            p = produced.get(c.lower()) or {}
            fields = p.get("fields") or {k: v for k, v in b["reads"].items() if k != "command"}
            msgs.append({"name": c, "payload": [{"name": "command", "type": "string"}] +
                         [{"name": n, "type": fields[n]} for n in sorted(fields) if n != "command"],
                         "producers": sorted(set(p.get("producers") or []))[:10]})
        cid = re.sub(r"[^a-z0-9]+", "-", b["destination"].lower()).strip("-")
        out.append({"id": cid, "destination": b["destination"], "kind": b["kind"], "consumer": b["class"],
                    "messages": msgs, "_file": b["file"]})
    return sorted(out, key=lambda c: c["id"])


# --- generators (each returns the files it wrote) ------------------------------------------------------------------

def _w(out: Path, name: str, text: str) -> Path:
    p = out / name
    p.write_text(text, encoding="utf-8", newline="\n")
    return p


def _app_name(app: dict) -> str:
    return re.sub(r"[^a-z0-9-]+", "-", str(app.get("name") or "app").lower()).strip("-") or "app"


def container_definition(a: dict, app: dict, env: list[dict], out: Path) -> list[Path]:
    st, name = a["stack"], _app_name(app)
    ports = [p["port"] for p in st["ports"]]
    lang = st["language"]
    lines = [f"# {HEADER}", (f"# Stack read: {lang} {st['version'] or '(level not declared)'}, "
             f"{st['framework'] or 'no framework detected'}, build {st['build_tool'] or 'none found'}, "
             f"packaging {st['packaging'] or 'unknown'}."), f"# Target runtime: {st['runtime'] or 'unknown'}.",
             "# Base images are placeholders: use the site's approved, hardened images.", ""]
    if lang == "java":
        mvn = (st["build_tool"] or "").startswith("maven")
        lines += ["ARG BUILD_IMAGE=maven:3-eclipse-temurin-17" if mvn else "ARG BUILD_IMAGE=gradle:8-jdk17",
                  ("ARG RUNTIME_IMAGE=open-liberty:full-java17-openj9" if "application server" in (st["runtime"] or "")
                   else "ARG RUNTIME_IMAGE=eclipse-temurin:17-jre" if a["boot"] else "ARG RUNTIME_IMAGE=tomcat:10-jre17"),
                  "", "FROM ${BUILD_IMAGE} AS build", "WORKDIR /src", "COPY . .",
                  ("RUN mvn -B -DskipTests package" if mvn else "RUN gradle --no-daemon -x test build")]
        art = {"ear": "*.ear", "war": "*.war"}.get(st["packaging"] or "", "*.jar")
        dest = ("/config/apps/" if "application server" in (st["runtime"] or "") else
                "/app/" if a["boot"] else "/usr/local/tomcat/webapps/")
        lines += [f"RUN mkdir /out && find . -path '*/{'target' if mvn else 'build/libs'}/{art}' -exec cp {{}} /out/ \\;", "",
                  "FROM ${RUNTIME_IMAGE}", f"COPY --from=build /out/ {dest}"]
        if a["liberty"]:
            lines += [f"COPY --from=build /src/{a['liberty'][0]} /config/server.xml"]
    elif lang == "csharp":
        proj = a["csprojs"][0] if a["csprojs"] else "App.csproj"
        lines += ["ARG BUILD_IMAGE=dotnet/sdk:8.0", "ARG RUNTIME_IMAGE=dotnet/aspnet:8.0", "",
                  "# Builds the .NET 8 project the version migration generates: the .NET Framework source does not",
                  "# build on .NET 8 as it is.", "FROM ${BUILD_IMAGE} AS build", "WORKDIR /src", "COPY . .",
                  f"RUN dotnet publish {proj} -c Release -o /out", "", "FROM ${RUNTIME_IMAGE}", "WORKDIR /app",
                  "COPY --from=build /out .", f'ENTRYPOINT ["dotnet", "{Path(proj).stem}.dll"]']
    else:
        lines += ["# No container recipe for this language: nothing more is generated.", "FROM scratch"]
    lines += ["", "# Configuration comes from the environment (env.mapping.json), never baked into the image:"]
    lines += [f"#   {e['name']}{'  (secret: from the secret store)' if e['secret'] else ''}" for e in env[:40]]
    if len(env) > 40:
        lines += [f"#   ... and {len(env) - 40} more"]
    lines += ["USER 1001", *(f"EXPOSE {p}" for p in ports), ""]
    cf = _w(out, "Containerfile", "\n".join(lines))
    plain = [e["name"] for e in env if not e["secret"]]
    dep = {"apiVersion": "apps/v1", "kind": "Deployment",
           "metadata": {"name": name, "labels": {"app": name, "icdev.generated": "unreviewed"}},
           "spec": {"replicas": 1, "selector": {"matchLabels": {"app": name}},
                    "template": {"metadata": {"labels": {"app": name}},
                                 "spec": {"securityContext": {"runAsNonRoot": True},
                                          "containers": [{"name": name, "image": f"{name}:unreviewed",
                                                          "ports": [{"containerPort": p} for p in ports],
                                                          "envFrom": ([{"configMapRef": {"name": f"{name}-config"}}] if plain else [])
                                                          + ([{"secretRef": {"name": f"{name}-secrets"}}]
                                                             if any(e["secret"] for e in env) else []),
                                                          "securityContext": {"allowPrivilegeEscalation": False,
                                                                              "readOnlyRootFilesystem": True}}]}}}}
    svc = {"apiVersion": "v1", "kind": "Service", "metadata": {"name": name},
           "spec": {"selector": {"app": name}, "ports": [{"port": p, "targetPort": p} for p in ports]}}
    body = (f"# {HEADER}\n# A minimal Deployment and Service. Readiness and liveness are left out: what the application "
            "answers on is seen running, not in source.\n" + yaml.safe_dump(dep, sort_keys=False) + "---\n"
            + yaml.safe_dump(svc, sort_keys=False))
    return [cf, _w(out, "deployment.yaml", body)]


def config_externalisation(a: dict, env: list[dict], out: Path) -> list[Path]:
    doc = {"generated": HEADER, "tool": TOOL, "findings": a["findings"], "total": a["findings_total"],
           "shown": len(a["findings"]), "note": "locations only: no value is copied, a credential least of all"}
    ex = [f"# {HEADER}", "# One variable per hard-coded setting found (env.mapping.json says where each is). No value",
          "# is given: a secret comes from the secret store, the rest from the deployment's configuration.", ""]
    ex += [f"# secret: {e['name']}=" if e["secret"] else f"{e['name']}=" for e in env]
    return [_w(out, "config-findings.json", json.dumps(doc, indent=2) + "\n"),
            _w(out, "env.mapping.json", json.dumps({"generated": HEADER, "env": env}, indent=2) + "\n"),
            _w(out, "config.env.example", "\n".join(ex) + "\n")]


def twelve_factor_report(a: dict, out: Path) -> list[Path]:
    fs = twelve_factor(a)
    doc = {"generated": HEADER, "tool": TOOL, "stack": a["stack"], "factors": fs,
           "counts": {s: sum(f["status"] == s for f in fs) for s in ("met", "not_met", "unverified")}}
    return [_w(out, "twelve-factor.json", json.dumps(doc, indent=2) + "\n")]


def event_contract(a: dict, app: dict, out: Path) -> list[Path]:
    chans = events(a)
    if not chans:
        raise RuntimeError("no message-driven bean with a destination was found in the source")
    api = {"asyncapi": "2.6.0",
           "info": {"title": f"{app.get('name') or 'application'} events (proposed)", "version": "0.1.0-unreviewed",
                    "description": HEADER + " Each channel is a message-driven bean's destination; each message, a "
                                            "command the bean dispatches on. A proposal, not a contract anyone agreed."},
           "channels": {}}
    for c in chans:
        msgs = {m["name"]: {"name": m["name"], "payload": {"type": "object", "required": ["command"],
                                                         "properties": {f["name"]: {"type": f["type"]} for f in m["payload"]}}}
                for m in c["messages"]}
        op = {"operationId": f"on_{re.sub(r'[^A-Za-z0-9]+', '_', c['destination'])}",
              "message": {"oneOf": list(msgs.values())} if len(msgs) > 1 else next(iter(msgs.values()))}
        api["channels"][c["destination"]] = {"description": f"{c['kind']} read by {c['consumer']} ({c['_file']})",
                                             "subscribe": op}
    doc = {"generated": HEADER, "tool": TOOL,
           "channels": [{k: v for k, v in c.items() if not k.startswith("_")} for c in chans]}
    return [_w(out, "asyncapi.yaml", f"# {HEADER}\n" + yaml.safe_dump(api, sort_keys=False)),
            _w(out, "event-contract.json", json.dumps(doc, indent=2) + "\n")]


def generate(scaffold: str, *, source: str, app: dict, out: Path) -> tuple[list[Path], str]:
    """Run one cloud-native job: (the files written, a one-line summary). ``app``: the CAM inventory row (name,
    language, version, framework)."""
    if scaffold not in SCAFFOLDS:
        raise ValueError(f"no cloud-native job {scaffold!r}")
    if not source or not Path(source).is_dir():
        raise RuntimeError("the job needs the application's source tree (source_repo), which is not readable here")
    out.mkdir(parents=True, exist_ok=True)
    a = analyse(source, language=app.get("language") or "", version=app.get("version") or "",
                framework=app.get("framework") or "")
    env = env_mapping(a["findings"])
    if scaffold == "container_definition":
        files = container_definition(a, app, env, out)
        return files, (f"container definition for {a['stack']['runtime'] or 'an unknown runtime'}, ports "
                       f"{', '.join(str(p['port']) for p in a['stack']['ports']) or 'none'}: generated, unreviewed")
    if scaffold == "config_externalisation":
        files = config_externalisation(a, env, out)
        return files, (f"{a['findings_total']} hard-coded setting(s) found, mapped to {len(env)} environment "
                       f"variable(s): locations only, generated, unreviewed")
    if scaffold == "twelve_factor_report":
        files = twelve_factor_report(a, out)
        c = json.loads(files[0].read_text())["counts"]
        return files, f"twelve factors: {c['met']} met, {c['not_met']} not met, {c['unverified']} unverified"
    files = event_contract(a, app, out)
    ch = json.loads(files[1].read_text())["channels"]
    return files, (f"{len(ch)} message-driven destination(s) proposed as event channels, "
                   f"{sum(len(c['messages']) for c in ch)} message(s): generated, unreviewed")


# --- the plan's target ---------------------------------------------------------------------------------------------

#: target phrase (lower-case, matched as a substring) -> (what proposes it, the factors it rests on)
TARGET_RULES = (
    ("container", (["container_definition", "deployment_manifest"], ["port_binding", "processes", "disposability"])),
    ("twelve-factor", (["twelve_factor_report", "config_mapping"], ["config"])),
    ("12-factor", (["twelve_factor_report", "config_mapping"], ["config"])),
    ("managed postgres", (["db_ddl_generation"], ["backing_services", "dev_prod_parity"])),
    ("postgres", (["db_ddl_generation"], ["backing_services"])),
    ("event", (["event_contract"], [])),
    ("stateless", ([], ["processes"])),
    ("java 1", (["version_upgrade"], [])),
    (".net", (["version_upgrade"], [])),
)


def targets(declared: dict, generated: set[str], existing: list[str] = ()) -> list[dict]:
    """Each declared target item and what proposes it: ``generated`` when a generated, unreviewed artefact kind or a
    refactor job kind in ``generated`` proposes it, else ``not_addressed``. Never ``reached``. ``existing``: container
    or deployment files already in the source -- read, never built, so they reach nothing either."""
    out = []
    for kind in ("cloud", "ai"):
        for t in declared.get(kind) or []:
            low = str(t).lower()
            rule = next((r for k, r in TARGET_RULES if k in low), None) if kind == "cloud" else None
            by = [x for x in (rule[0] if rule else []) if x in generated]
            factors = list(rule[1]) if rule else []
            if by:
                why = f"proposed by {', '.join(by)}: generated, unreviewed; not reached until it runs so"
                if "container_definition" in by and existing:
                    why += (f" (the source already carries {', '.join(list(existing)[:3])}"
                            f"{' …' if len(existing) > 3 else ''}: read, never built)")
            elif kind == "ai":
                why = ("AI-Ify reports code patterns, not this use case: its opportunities are drafted as AI use "
                       "cases separately, and a person may draft this one")
            elif rule and not rule[0]:
                why = f"no tool generates it; the twelve-factor report scores {', '.join(factors)}"
            else:
                why = "no tool proposes it"
            out.append({"target": str(t), "kind": kind, "status": "generated" if by else "not_addressed",
                        "by": by, "factors": factors, "why": why})
    return out
