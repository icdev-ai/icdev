def main():
    parser = argparse.ArgumentParser(description="IDC IaC Generator — Step 3")
    parser.add_argument("--project-id", default="default")
    parser.add_argument("--run-id", default="")
    parser.add_argument("--canvas", default=_CANVAS)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    try:
        ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        uid = uuid.uuid4().hex[:8]

        _ARTIFACTS_DIR.mkdir(parents=True, exist_ok=True)
        tf_dir = _ARTIFACTS_DIR / "terraform"
        tf_dir.mkdir(parents=True, exist_ok=True)

        tf_main_path = tf_dir / f"main_{uid}.tf"
        tf_vars_path = tf_dir / "variables.tf"
        tf_tfvars_path = tf_dir / "terraform.tfvars.example"
        ansible_path = _ARTIFACTS_DIR / f"ansible_playbook_{uid}.yml"
        validate_path = _ARTIFACTS_DIR / f"validate_{uid}.py"
        report_path = _ARTIFACTS_DIR / f"iac_report_{uid}.md"

        tf_main_path.write_text(_TF_MAIN.format(ts=ts), encoding="utf-8", newline="")
        tf_vars_path.write_text(_TF_VARIABLES, encoding="utf-8", newline="")
        tf_tfvars_path.write_text(_TFVARS_EXAMPLE, encoding="utf-8", newline="")
        ansible_path.write_text(_ANSIBLE_PLAYBOOK.format(ts=ts), encoding="utf-8", newline="")
        validate_path.write_text(_VALIDATION_SCRIPT.format(ts=ts, uid=uid), encoding="utf-8", newline="")
        report_path.write_text(_IAC_REPORT.format(
            ts=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
            tf_main=tf_main_path.relative_to(_ROOT).as_posix(),
            tf_vars=tf_vars_path.relative_to(_ROOT).as_posix(),
            tf_tfvars=tf_tfvars_path.relative_to(_ROOT).as_posix(),
            ansible_pb=ansible_path.relative_to(_ROOT).as_posix(),
            validate_py=validate_path.relative_to(_ROOT).as_posix(),
            iac_report=report_path.relative_to(_ROOT).as_posix(),
        ), encoding="utf-8", newline="")

        output = {
            "gate": "PASS",
            "canvas": args.canvas,
            "artifacts": [
                {
                    "name": "Terraform Main",
                    "path": tf_main_path.relative_to(_ROOT).as_posix(),
                    "type": "tf",
                },
                {
                    "name": "Terraform Variables",
                    "path": tf_vars_path.relative_to(_ROOT).as_posix(),
                    "type": "tf",
                },
                {
                    "name": "Terraform tfvars example",
                    "path": tf_tfvars_path.relative_to(_ROOT).as_posix(),
                    "type": "tf",
                },
                {
                    "name": "Ansible Hardening Playbook",
                    "path": ansible_path.relative_to(_ROOT).as_posix(),
                    "type": "yml",
                },
                {
                    "name": "Validation Script",
                    "path": validate_path.relative_to(_ROOT).as_posix(),
                    "type": "py",
                },
                {
                    "name": "IaC Generation Report",
                    "path": report_path.relative_to(_ROOT).as_posix(),
                    "type": "md",
                },
            ],
        }
        print(json.dumps(output))
        sys.exit(0)
    except Exception as exc:
        print(json.dumps({"status": "failed", "error": str(exc)}))
        sys.exit(1)


if __name__ == "__main__":
    main()
