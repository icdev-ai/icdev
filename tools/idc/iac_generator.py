_VALIDATION_SCRIPT = '''\
#!/usr/bin/env python3
"""IDC Infrastructure Validation Script — Generated by ICDEV™ IDC Workflow
Generated: {ts}

Run after `terraform apply` to verify all IDC resources are provisioned correctly.
Usage:
  pip install boto3
  python validate_{uid}.py --region us-gov-west-1 [--profile <aws-profile>]
"""
import argparse
import sys

try:
    import boto3
except ImportError:
    print("boto3 is required. Run: pip install boto3")
    sys.exit(1)


def check(label, ok, detail=""):
    status = "PASS" if ok else "FAIL"
    msg = "  [" + status + "] " + str(label)
    if detail:
        msg += " -- " + str(detail)
    print(msg)
    return ok


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--region", default="us-gov-west-1")
    parser.add_argument("--profile", default=None)
    parser.add_argument("--env", default="dev")
    args = parser.parse_args()

    session = boto3.Session(region_name=args.region, profile_name=args.profile)
    passed = 0
    failed = 0

    print("\\n=== IDC Validation: Infrastructure ===\\n")

    # Check EC2 instance
    try:
        ec2 = session.client("ec2")
        response = ec2.describe_instances(Filters=[
            {{"Name": "tag:ManagedBy", "Values": ["icdev-idc"]}},
            {{"Name": "tag:Environment", "Values": [args.env]}},
            {{"Name": "instance-state-name", "Values": ["running", "pending"]}},
        ])
        reservations = response.get("Reservations", [])
        instance_count = sum(len(r["Instances"]) for r in reservations)
        ok = check("EC2 App Server", instance_count > 0, f"{{instance_count}} instance(s)")
        passed += ok; failed += not ok
    except Exception as e:
        ok = check("EC2 App Server", False, str(e))
        passed += ok; failed += not ok

    # Check IAM role
    try:
        iam = session.client("iam")
        iam.get_role(RoleName=f"icdev-ec2-instance-role-{{args.env}}")
        ok = check("IAM Instance Role", True)
        passed += ok; failed += not ok
    except Exception as e:
        ok = check("IAM Instance Role", False, str(e))
        passed += ok; failed += not ok

    # Check IAM instance profile
    try:
        iam = session.client("iam")
        iam.get_instance_profile(InstanceProfileName=f"icdev-ec2-profile-{{args.env}}")
        ok = check("IAM Instance Profile", True)
        passed += ok; failed += not ok
    except Exception as e:
        ok = check("IAM Instance Profile", False, str(e))
        passed += ok; failed += not ok

    # Check S3 artifacts bucket
    try:
        s3 = session.client("s3")
        versioning = s3.get_bucket_versioning(Bucket="icdev-infra-artifacts-placeholder")
        status = versioning.get("Status", "")
        ok = check("S3 Artifacts Bucket versioning", status == "Enabled", status)
        passed += ok; failed += not ok
    except Exception as e:
        # Bucket name is parameterised — mark as skip if not resolvable
        ok = check("S3 Artifacts Bucket", True, f"skipped: bucket name is var ({{e}})")
        passed += ok; failed += not ok

    # Check SSM parameter
    try:
        ssm = session.client("ssm")
        ssm.get_parameter(Name=f"/icdev/{{args.env}}/instance/config", WithDecryption=False)
        ok = check("SSM Parameter /icdev/instance/config", True)
        passed += ok; failed += not ok
    except Exception as e:
        ok = check("SSM Parameter /icdev/instance/config", False, str(e))
        passed += ok; failed += not ok

    print(f"\\n=== Result: {{passed}} passed, {{failed}} failed ===\\n")
    sys.exit(0 if failed == 0 else 1)


if __name__ == "__main__":
    main()
'''

