"""Terraform Executor — DDC Workflow Step 5.

Validates and dry-plans the Terraform generated by iac_generator using
Docker (hashicorp/terraform:1.9). No AWS credentials needed — runs
`terraform fmt -check` + `terraform init -backend=false` + `terraform validate`.

Falls back to HCL syntax-only check if Docker is unavailable.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
import uuid
from datetime import datetime, timezone
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(_ROOT))

_ARTIFACTS_DIR = _ROOT / "data" / "studio_artifacts" / "ddc"
_TF_IMAGE = "hashicorp/terraform:1.9"


def _get_iac_artifacts(run_id: str, project_id: str) -> list[dict]:
    """Find artifacts from the Generate IaC step in this run."""
    try:
        from tools.db.storage import get_connection
        conn = get_connection()
        try:
            row = conn.execute(
                "SELECT stdout FROM studio_workflow_run_steps "
                "WHERE run_id = %s AND step_name = 'Generate IaC'",
                (run_id,),
            ).fetchone()
            if row and row["stdout"]:
                return json.loads(row["stdout"]).get("artifacts", [])
        finally:
            conn.close()
    except Exception:
        pass
    # Fallback: latest .tf files for project
    tf_dir = _ARTIFACTS_DIR / "terraform"
    if tf_dir.exists():
        tfs = sorted(tf_dir.glob("main_*.tf"), key=lambda p: p.stat().st_mtime, reverse=True)
        if tfs:
            uid = tfs[0].stem.split("_", 1)[1]
            return [
                {"name": "Terraform Main", "path": f"data/studio_artifacts/ddc/terraform/main_{uid}.tf", "type": "tf"},
                {"name": "Terraform Variables", "path": f"data/studio_artifacts/ddc/terraform/variables_{uid}.tf", "type": "tf"},
            ]
    return []


def _docker_available() -> bool:
    try:
        subprocess.run(["docker", "info"], capture_output=True, timeout=5, check=True)
        return True
    except Exception:
        return False


def _pull_image() -> bool:
    """Pull terraform image if not already cached."""
    try:
        result = subprocess.run(
            ["docker", "image", "inspect", _TF_IMAGE],
            capture_output=True, timeout=10
        )
        if result.returncode == 0:
            return True
        subprocess.run(["docker", "pull", _TF_IMAGE], capture_output=True, timeout=120, check=True)
        return True
    except Exception:
        return False


def _docker_run(workspace: str, *args: str, timeout: int = 120) -> tuple[int, str, str]:
    """Run terraform in Docker with workspace mounted."""
    # Convert Windows path to Docker-compatible format
    ws_path = Path(workspace).as_posix()
    cmd = [
        "docker", "run", "--rm",
        "-v", f"{ws_path}:/workspace",
        "-w", "/workspace",
        "--entrypoint", "terraform",
        _TF_IMAGE,
        *args,
    ]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        return r.returncode, r.stdout, r.stderr
    except subprocess.TimeoutExpired:
        return 1, "", f"Docker command timed out after {timeout}s"
    except Exception as e:
        return 1, "", str(e)


def _hcl_syntax_check(tf_files: list[Path]) -> tuple[bool, str]:
    """Fallback: parse HCL files as text, check basic structure."""
    issues = []
    for f in tf_files:
        text = f.read_text(encoding="utf-8")
        # Count braces
        opens = text.count("{")
        closes = text.count("}")
        if opens != closes:
            issues.append(f"{f.name}: mismatched braces ({opens} open, {closes} close)")
    if issues:
        return False, "\n".join(issues)
    return True, f"HCL brace check passed for {len(tf_files)} file(s)"


def run_terraform(run_id: str, project_id: str) -> dict:
    artifacts = _get_iac_artifacts(run_id, project_id)
    tf_artifacts = [a for a in artifacts if a.get("type") == "tf"]

    findings: list[dict] = []
    gate = "PASS"
    docker_used = False

    # Resolve local paths
    tf_paths = []
    for a in tf_artifacts:
        p = _ROOT / a["path"]
        if p.exists():
            tf_paths.append(p)

    if not tf_paths:
        return {
            "gate": "WARN",
            "findings": [{"severity": "warn", "check": "no_tf_files",
                          "message": "No Terraform files found from IaC step"}],
            "docker_used": False,
        }

    use_docker = _docker_available()
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    uid = uuid.uuid4().hex[:8]

    if use_docker and _pull_image():
        docker_used = True
        # Copy .tf files into a temp workspace
        with tempfile.TemporaryDirectory() as tmp:
            for p in tf_paths:
                shutil.copy2(p, Path(tmp) / p.name)

            # Step 1: fmt -check
            rc, out, err = _docker_run(tmp, "fmt", "-check", "-diff", "-no-color")
            if rc != 0:
                findings.append({"severity": "warn", "check": "terraform_fmt",
                                  "message": f"Formatting issues:\n{out or err}"})
            else:
                findings.append({"severity": "pass", "check": "terraform_fmt",
                                  "message": "HCL formatting OK"})

            # Step 2: init -backend=false (downloads providers)
            rc, out, err = _docker_run(tmp, "init", "-backend=false", "-input=false",
                                        "-no-color", timeout=180)
            if rc != 0:
                findings.append({"severity": "warn", "check": "terraform_init",
                                  "message": f"Init failed (non-blocking): {err[:500]}"})
            else:
                # Step 3: validate
                rc, out, err = _docker_run(tmp, "validate", "-json")
                if rc == 0:
                    try:
                        vdata = json.loads(out)
                        if vdata.get("valid"):
                            findings.append({"severity": "pass", "check": "terraform_validate",
                                              "message": f"Validated {vdata.get('format_version','?')}: no errors"})
                        else:
                            for diag in vdata.get("diagnostics", []):
                                sev = "fail" if diag.get("severity") == "error" else "warn"
                                findings.append({"severity": sev, "check": "terraform_validate",
                                                  "message": diag.get("summary", diag.get("detail", ""))})
                                if sev == "fail":
                                    gate = "FAIL"
                    except json.JSONDecodeError:
                        findings.append({"severity": "warn", "check": "terraform_validate",
                                          "message": f"validate returned non-JSON: {out[:300]}"})
                else:
                    findings.append({"severity": "fail", "check": "terraform_validate",
                                      "message": err[:500] or out[:500]})
                    gate = "FAIL"
    else:
        # Fallback: brace/syntax heuristic
        ok, msg = _hcl_syntax_check(tf_paths)
        sev = "pass" if ok else "fail"
        findings.append({"severity": sev, "check": "hcl_syntax", "message": msg})
        if not ok:
            gate = "FAIL"
        findings.append({"severity": "info", "check": "docker_unavailable",
                          "message": "Docker not available — full terraform validate skipped"})

    # Build report
    fails = [f for f in findings if f["severity"] == "fail"]
    warns = [f for f in findings if f["severity"] == "warn"]
    passes = [f for f in findings if f["severity"] == "pass"]
    gate = gate if fails else "PASS"

    lines = [
        "# Terraform Plan Report",
        f"**Generated:** {ts}  ",
        f"**Project:** {project_id}  ",
        f"**Gate:** {'✓ PASS' if gate == 'PASS' else '✗ FAIL'}  ",
        f"**Docker:** {'Yes — ' + _TF_IMAGE if docker_used else 'No (fallback)'}  ",
        f"**Files checked:** {len(tf_paths)}",
        "",
    ]
    for grp, label in [(fails, "✗ Failures"), (warns, "⚠ Warnings"), (passes, "✓ Passed")]:
        if grp:
            lines.append(f"## {label}")
            for f in grp:
                lines.append(f"- **[{f['check']}]** {f['message'][:200]}")
            lines.append("")

    _ARTIFACTS_DIR.mkdir(parents=True, exist_ok=True)
    report_path = _ARTIFACTS_DIR / f"terraform_report_{uid}.md"
    report_path.write_text("\n".join(lines), encoding="utf-8", newline="")

    return {
        "gate": gate,
        "findings": findings,
        "docker_used": docker_used,
        "tf_files_checked": len(tf_paths),
        "report_path": report_path.relative_to(_ROOT).as_posix(),
    }


def main():
    parser = argparse.ArgumentParser(description="Terraform Executor")
    parser.add_argument("--project-id", default="default")
    parser.add_argument("--run-id", default="")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    try:
        result = run_terraform(args.run_id, args.project_id)
        gate = result["gate"]

        output = {
            "status": "success" if gate == "PASS" else "failed",
            "gate": gate,
            "docker_used": result["docker_used"],
            "tf_files_checked": result["tf_files_checked"],
            "findings": len(result["findings"]),
            "failures": sum(1 for f in result["findings"] if f["severity"] == "fail"),
            "artifacts": [
                {"name": "Terraform Plan Report", "path": result["report_path"], "type": "md"},
            ],
        }
        print(json.dumps(output))
        sys.exit(0 if gate == "PASS" else 1)
    except Exception as exc:
        print(json.dumps({"status": "failed", "error": str(exc)}))
        sys.exit(1)


if __name__ == "__main__":
    main()
