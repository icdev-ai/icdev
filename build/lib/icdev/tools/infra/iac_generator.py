# CUI // SP-CTI
"""Terraform IaC generator for IDC canvas design JSON.

Pure function: generate_terraform(design_json) -> str (HCL).

Node type mapping:
  vm  -> aws_instance
  lb  -> aws_lb
  rds -> aws_db_instance
  s3  -> aws_s3_bucket
"""

import json
import re
from datetime import datetime, timezone


_TYPE_MAP = {
    "vm": "aws_instance",
    "lb": "aws_lb",
    "rds": "aws_db_instance",
    "s3": "aws_s3_bucket",
}


def _slug(label: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9_]", "_", str(label).strip())
    s = re.sub(r"_+", "_", s).strip("_").lower()
    return s or "resource"


def _tf_block(node: dict) -> str:
    ntype = node.get("type", "")
    label = node.get("label", ntype)
    name = _slug(label)

    if ntype == "vm":
        return (
            f'resource "aws_instance" "{name}" {{\n'
            f'  ami           = var.ami_id\n'
            f'  instance_type = "t3.medium"\n'
            f"  root_block_device {{\n"
            f"    encrypted = true\n"
            f"  }}\n"
            f'  tags = {{ Name = "{label}", Classification = "CUI" }}\n'
            f"}}\n"
        )

    if ntype == "lb":
        return (
            f'resource "aws_lb" "{name}" {{\n'
            f'  internal           = false\n'
            f'  load_balancer_type = "application"\n'
            f'  tags = {{ Name = "{label}", Classification = "CUI" }}\n'
            f"}}\n"
        )

    if ntype == "rds":
        return (
            f'resource "aws_db_instance" "{name}" {{\n'
            f'  engine            = "postgres"\n'
            f'  instance_class    = "db.t3.medium"\n'
            f'  storage_encrypted = true\n'
            f'  tags = {{ Name = "{label}", Classification = "CUI" }}\n'
            f"}}\n"
        )

    if ntype == "s3":
        bucket = name + "-bucket"
        return (
            f'resource "aws_s3_bucket" "{name}" {{\n'
            f'  bucket = "{bucket}"\n'
            f'  tags = {{ Name = "{label}", Classification = "CUI" }}\n'
            f"}}\n"
        )

    # Unknown type — emit a comment so the output is still valid HCL
    return f"# Unsupported node type: {ntype!r} (label={label!r})\n"


def generate_terraform(design_json) -> str:
    """Return Terraform HCL for every node in design_json.

    Args:
        design_json: dict {nodes: [...], edges: [...]} or JSON string.

    Returns:
        HCL string.
    """
    if isinstance(design_json, (str, bytes)):
        design_json = json.loads(design_json)

    nodes = design_json.get("nodes", [])
    ts = datetime.now(timezone.utc).isoformat()

    parts = [
        "# CUI // SP-CTI",
        f"# Generated by ICDEV IaC Generator — {ts}",
        "",
        'variable "ami_id" { default = "ami-0abcdef1234567890" }',
        "",
    ]

    for node in nodes:
        parts.append(_tf_block(node))

    return "\n".join(parts)
