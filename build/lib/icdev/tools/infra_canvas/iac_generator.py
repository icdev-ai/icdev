def _ansible_task(node: dict) -> str:
    """Return Ansible task YAML for a single IDC node."""
    ntype = node.get("type", "")
    label = node.get("label", ntype)

    # VM/server nodes get STIG hardening tasks
    if ntype in ("aws-ec2", "aws-ec2-spot", "az-vm", "az-spot", "gcp-gce", "gcp-spot",
                  "oci-compute", "oci-preemptible", "ibm-vsi", "op-server", "op-vm"):
        host = _node_data(node, "hostname", _slug(label))
        return (
            f"    # --- {label} ---\n"
            f"    - name: Apply STIG hardening — {label}\n"
            f"      ansible.builtin.include_role:\n"
            f"        name: hardening\n"
            f"      vars:\n"
            f'        target_host: "{host}"\n'
            f'        classification: "CUI"\n'
            f"\n"
            f"    - name: Enable auditd — {label}\n"
            f"      ansible.builtin.service:\n"
            f"        name: auditd\n"
            f"        state: started\n"
            f"        enabled: true\n"
            f"\n"
            f"    - name: Disable unnecessary services — {label}\n"
            f"      ansible.builtin.service:\n"
            f"        name: '{{ item }}'\n"
            f"        state: stopped\n"
            f"        enabled: false\n"
            f"      loop: [bluetooth, cups, avahi-daemon]\n"
            f"      ignore_errors: true\n\n"
        )

    # K8s clusters get kubeadm/kubectl post-setup
    if ntype in ("aws-eks", "aws-eks-managed", "az-aks", "gcp-gke", "oci-oke", "ibm-iks",
                  "op-k8s-cluster"):
        return (
            f"    # --- {label} (K8s) ---\n"
            f"    - name: Apply PodSecurityAdmission labels — {label}\n"
            f"      ansible.builtin.shell: |\n"
            f"        kubectl label namespace default \\\n"
            f'          pod-security.kubernetes.io/enforce=restricted \\\n'
            f'          pod-security.kubernetes.io/warn=restricted\n'
            f"      ignore_errors: true\n"
            f"\n"
            f"    - name: Apply network policy deny-all baseline — {label}\n"
            f"      kubernetes.core.k8s:\n"
            f"        state: present\n"
            f"        definition:\n"
            f"          apiVersion: networking.k8s.io/v1\n"
            f"          kind: NetworkPolicy\n"
            f"          metadata:\n"
            f'            name: deny-all\n'
            f'            namespace: default\n'
            f"          spec:\n"
            f"            podSelector: {{}}\n"
            f"            policyTypes: [Ingress, Egress]\n\n"
        )

    # Storage nodes — verify encryption
    if ntype in ("aws-s3", "aws-ebs", "aws-efs", "az-blob", "az-files", "az-disk",
                  "gcp-gcs", "oci-os", "ibm-cos", "op-san", "op-nas", "op-s3-compat"):
        return (
            f"    # --- {label} (storage) ---\n"
            f"    - name: Verify encryption for {label}\n"
            f"      ansible.builtin.debug:\n"
            f'        msg: "Storage {label} provisioned — verify KMS encryption in cloud console"\n\n'
        )

    # Database nodes — verify encryption + backup
    if "rds" in ntype or "sql" in ntype or "cosmos" in ntype or "postgres" in ntype or "mysql" in ntype:
        return (
            f"    # --- {label} (database) ---\n"
            f"    - name: Verify database encryption — {label}\n"
            f"      ansible.builtin.debug:\n"
            f'        msg: "Database {label} — confirm encryption-at-rest and automated backups in cloud console"\n\n'
        )

    # Generic placeholder
    return (
        f"    # --- {label} [{ntype}] ---\n"
        f"    - name: Post-provisioning check — {label}\n"
        f"      ansible.builtin.debug:\n"
        f'        msg: "Resource {label} ({ntype}) provisioned — verify configuration"\n\n'
    )


def generate_ansible(graph: dict) -> str:
    """Emit an Ansible site.yml playbook for all nodes in an IDC graph."""
    nodes = graph.get("nodes", [])

    parts = [_ANSIBLE_HEADER.format(ts=_ts())]

    # Inventory group detection
    k8s_nodes = [n for n in nodes if "eks" in n.get("type", "") or "aks" in n.get("type", "")
                 or "gke" in n.get("type", "") or "oke" in n.get("type", "")
                 or "iks" in n.get("type", "") or "k8s" in n.get("type", "")]
    # Play 1: Common hardening for all managed hosts
    parts.append(
        "- name: ICDEV IDC — Common Security Baseline\n"
        "  hosts: all\n"
        "  gather_facts: true\n"
        "  become: true\n"
        "  vars:\n"
        "    classification: CUI\n"
        "    icdev_managed: true\n"
        "  pre_tasks:\n"
        "    - name: Verify CUI classification tag\n"
        "      ansible.builtin.assert:\n"
        "        that: classification == 'CUI'\n"
        "        fail_msg: 'Classification must be CUI'\n"
        "  tasks:\n"
        "    - name: Update all packages (security patches)\n"
        "      ansible.builtin.package:\n"
        "        name: '*'\n"
        "        state: latest\n"
        "      when: ansible_os_family in ['RedHat', 'Debian']\n"
        "\n"
        "    - name: Install required packages\n"
        "      ansible.builtin.package:\n"
        "        name:\n"
        "          - aide\n"
        "          - audit\n"
        "          - firewalld\n"
        "          - openscap-scanner\n"
        "        state: present\n"
        "      when: ansible_os_family == 'RedHat'\n"
        "      ignore_errors: true\n\n"
    )

    # Play 2: Per-resource configuration
    if nodes:
        parts.append(
            "- name: ICDEV IDC — Per-Resource Post-Provisioning\n"
            "  hosts: all\n"
            "  gather_facts: false\n"
            "  become: true\n"
            "  tasks:\n"
        )
        for node in nodes:
            parts.append(_ansible_task(node))

    # Play 3: K8s-specific (if any K8s nodes)
    if k8s_nodes:
        parts.append(
            "- name: ICDEV IDC — Kubernetes Security Baseline\n"
            "  hosts: k8s_masters\n"
            "  gather_facts: false\n"
            "  tasks:\n"
        )
        for node in k8s_nodes:
            parts.append(_ansible_task(node))

    if not nodes:
        parts.append(
            "- name: ICDEV IDC — No resources configured\n"
            "  hosts: all\n"
            "  tasks:\n"
            "    - name: Placeholder\n"
            "      ansible.builtin.debug:\n"
            "        msg: 'No IDC resources — add nodes in the canvas'\n"
        )

    return "\n".join(parts)


