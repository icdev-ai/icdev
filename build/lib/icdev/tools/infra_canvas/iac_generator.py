def generate_helm(graph: dict) -> bytes:
    """Emit a Helm chart ZIP archive for K8s workloads in an IDC graph.

    Returns raw ZIP bytes. Caller base64-encodes and sets filename to
    <name>.tgz or <name>-helm.zip.
    """
    nodes = graph.get("nodes", [])
    chart_name = "icdev-infra"
    # Derive chart name from first K8s or container node
    for n in nodes:
        t = n.get("type", "")
        if any(t.startswith(p) for p in ("aws-eks", "az-aks", "gcp-gke", "oci-oke", "ibm-iks", "op-k8s")):
            chart_name = _slug(n.get("label", "infra"))
            break

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        prefix = f"{chart_name}/"
        zf.writestr(prefix + "Chart.yaml", _helm_chart_yaml(chart_name))
        zf.writestr(prefix + "values.yaml", _helm_values_yaml(nodes))
        zf.writestr(prefix + "templates/_helpers.tpl", _helm_helpers_tpl())
        zf.writestr(prefix + "templates/deployment.yaml", _helm_deployment_yaml())
        zf.writestr(prefix + "templates/service.yaml", _helm_service_yaml())
        zf.writestr(prefix + "templates/hpa.yaml", _helm_hpa_yaml())
        zf.writestr(prefix + "templates/networkpolicy.yaml", _helm_netpol_yaml())
        # README
        readme = (
            f"# {chart_name} Helm Chart\n\n"
            f"CUI // SP-CTI — Generated by ICDEV IDC IaC Generator\n\n"
            f"Generated: {_ts()}\n\n"
            f"## Install\n\n"
            f"```bash\nhelm install {chart_name} ./{chart_name}/ \\\n"
            f"  --namespace {chart_name} --create-namespace \\\n"
            f"  --set image.repository=your-registry/your-image \\\n"
            f"  --set image.tag=latest\n```\n\n"
            f"## Security\n\n"
            f"- Pods run as non-root (UID 1000)\n"
            f"- Read-only root filesystem\n"
            f"- All capabilities dropped\n"
            f"- NetworkPolicy deny-all by default\n"
            f"- PodSecurityContext with seccomp RuntimeDefault\n"
        )
        zf.writestr(prefix + "README.md", readme)

    return buf.getvalue()
