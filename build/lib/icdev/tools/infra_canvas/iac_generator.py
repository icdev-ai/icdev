# ── Helpers ────────────────────────────────────────────────────────────────────

_CUI_BANNER = """\
# CUI // SP-CTI
# CONTROLLED UNCLASSIFIED INFORMATION
# Generated by ICDEV IDC IaC Generator — {emitter}
# Timestamp: {ts}
# Classification: CUI — Authorized for internal project use only
# DO NOT distribute outside authorized channels
"""


def _ts() -> str:
    return datetime.now(timezone.utc).isoformat()


def _cui(emitter: str) -> str:
    return _CUI_BANNER.format(emitter=emitter, ts=_ts())


def _slug(label: str) -> str:
    """Sanitize a node label into a valid identifier."""
    s = re.sub(r"[^a-zA-Z0-9_]", "_", str(label).strip())
    s = re.sub(r"_+", "_", s).strip("_").lower()
    return s or "resource"


def _detect_csps(nodes: list) -> set:
    csps: set = set()
    for n in nodes:
        t = n.get("type", "")
        if t.startswith("aws"):
            csps.add("aws")
        elif t.startswith("az-"):
            csps.add("azure")
        elif t.startswith("gcp-"):
            csps.add("gcp")
        elif t.startswith("oci-"):
            csps.add("oci")
        elif t.startswith("ibm-"):
            csps.add("ibm")
        elif t.startswith("op-"):
            csps.add("onprem")
    return csps


def _node_data(node: dict, key: str, default):
    return (node.get("data") or {}).get(key, default)


