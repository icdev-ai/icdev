def generate_pulumi(graph: dict) -> str:
    """Emit a Pulumi Python program for all nodes in an IDC graph."""
    nodes = graph.get("nodes", [])
    csps = _detect_csps(nodes)

    imports = ["# /// script"]
    for csp in sorted(csps):
        imp = _PULUMI_IMPORTS.get(csp)
        if imp:
            imports.append(imp)

    parts = [
        _cui("Pulumi Python"),
        "\n".join(imports),
        "",
        _PULUMI_OPTS,
        "# ── Resources ────────────────────────────────────────────────────────────────\n",
    ]

    for node in nodes:
        parts.append(_pulumi_block(node))

    if not nodes:
        parts.append("# No resources in graph — add nodes in the IDC canvas to generate IaC.\n")

    # Export resource IDs
    parts.append("\n# ── Outputs ──────────────────────────────────────────────────────────────────")
    for node in nodes:
        n = _slug(node.get("label", node.get("type", "res")))
        ntype = node.get("type", "")
        if not ntype.startswith("op-"):
            parts.append(f'pulumi.export("{n}_id", {n}.id if hasattr({n}, "id") else "{n}")')

    return "\n".join(parts)


