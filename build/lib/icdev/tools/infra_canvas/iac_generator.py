def _cf_resource_block(node: dict) -> str:
    """Return a CloudFormation resource entry (YAML block) for an IDC node."""
    ntype = node.get("type", "")
    label = node.get("label", ntype)
    logical_id = re.sub(r"[^a-zA-Z0-9]", "", label.title()) or "Resource"

    mapping = _CF_RESOURCE_MAP.get(ntype)
    if not mapping:
        return f"  # {logical_id}: [{ntype}] — no CloudFormation mapping; add manually\n"

    cf_type, props = mapping
    lines = [f"  {logical_id}:"]
    lines.append(f"    Type: {cf_type}")
    lines.append("    Properties:")

    def _emit_props(d: dict, indent: int) -> list:
        result = []
        pad = " " * indent
        for k, v in d.items():
            if isinstance(v, dict):
                result.append(f"{pad}{k}:")
                result.extend(_emit_props(v, indent + 2))
            elif isinstance(v, list):
                result.append(f"{pad}{k}:")
                for item in v:
                    if isinstance(item, dict):
                        first = True
                        for ik, iv in item.items():
                            prefix = "- " if first else "  "
                            result.append(f"{pad}  {prefix}{ik}: {iv}")
                            first = False
                    else:
                        result.append(f"{pad}  - {item}")
            else:
                result.append(f"{pad}{k}: {v}")
        return result

    lines.extend(_emit_props(props, 6))
    lines.append("      Tags:")
    lines.append("        - Key: Name")
    lines.append(f"          Value: {label}")
    lines.append("        - Key: Classification")
    lines.append("          Value: CUI")
    lines.append("")
    return "\n".join(lines) + "\n"


