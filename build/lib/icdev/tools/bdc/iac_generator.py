_VALIDATION_SCRIPT = '''\
#!/usr/bin/env python3
"""BDC Boundary Infrastructure Validation Script — Generated by ICDEV™ BDC Workflow
Generated: {ts}

Run after `terraform apply` to verify all BDC resources are provisioned correctly.
Usage:
  pip install boto3
  python validate_{uid}.py --region us-gov-west-1 [--profile <aws-profile>]
"""
import argparse
import sys

try:
    import boto3
except ImportError:
    print("boto3 is required. Run: pip install boto3")
    sys.exit(1)


def check(label, ok, detail=""):
    status = "PASS" if ok else "FAIL"
    msg = "  [" + status + "] " + str(label)
    if detail:
        msg += " -- " + str(detail)
    print(msg)
    return ok


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--region", default="us-gov-west-1")
    parser.add_argument("--profile", default=None)
    parser.add_argument("--boundary-name", default="icdev-boundary")
    parser.add_argument("--vpc-id", default="")
    args = parser.parse_args()

    session = boto3.Session(region_name=args.region, profile_name=args.profile)
    passed = 0
    failed = 0

    print("\\n=== BDC Validation: Authorization Boundary ===\\n")

    # Check VPC endpoints
    try:
        ec2 = session.client("ec2")
        endpoints = ec2.describe_vpc_endpoints(Filters=[
            {{"Name": "tag:ManagedBy", "Values": ["icdev-bdc"]}},
            {{"Name": "vpc-endpoint-state", "Values": ["available", "pending"]}},
        ])["VpcEndpoints"]
        ep_types = set(e["VpcEndpointType"] for e in endpoints)
        has_gateway = "Gateway" in ep_types
        has_interface = "Interface" in ep_types
        ok = check("VPC Endpoints (Gateway + Interface)", has_gateway and has_interface,
                   str(len(endpoints)) + " endpoint(s): " + ", ".join(ep_types))
        passed += ok; failed += not ok
    except Exception as e:
        ok = check("VPC Endpoints", False, str(e))
        passed += ok; failed += not ok

    # Check NACLs
    try:
        ec2 = session.client("ec2")
        nacls = ec2.describe_network_acls(Filters=[
            {{"Name": "tag:ManagedBy", "Values": ["icdev-bdc"]}},
        ])["NetworkAcls"]
        ok = check("Network ACLs (boundary enforcement)", len(nacls) > 0, str(len(nacls)) + " NACL(s)")
        passed += ok; failed += not ok
    except Exception as e:
        ok = check("Network ACLs", False, str(e))
        passed += ok; failed += not ok

    # Check KMS key
    try:
        kms = session.client("kms")
        key_alias = "alias/icdev-" + args.boundary_name + "-boundary"
        aliases = kms.list_aliases()["Aliases"]
        found = any(a.get("AliasName") == key_alias for a in aliases)
        ok = check("KMS Key Alias (" + key_alias + ")", found)
        passed += ok; failed += not ok
    except Exception as e:
        ok = check("KMS Key", False, str(e))
        passed += ok; failed += not ok

    # Check SSM boundary config parameter
    try:
        ssm = session.client("ssm")
        ssm.get_parameter(
            Name="/icdev/boundary/" + args.boundary_name + "/config",
            WithDecryption=False
        )
        ok = check("SSM Boundary Config (/icdev/boundary/" + args.boundary_name + "/config)", True)
        passed += ok; failed += not ok
    except Exception as e:
        ok = check("SSM Boundary Config", False, str(e))
        passed += ok; failed += not ok

    # Check boundary connectivity — verify no 0.0.0.0/0 ingress on boundary SGs
    try:
        ec2 = session.client("ec2")
        sgs = ec2.describe_security_groups(Filters=[
            {{"Name": "tag:ManagedBy", "Values": ["icdev-bdc"]}},
        ])["SecurityGroups"]
        open_ingress = []
        for sg in sgs:
            for perm in sg.get("IpPermissions", []):
                for ip_range in perm.get("IpRanges", []):
                    if ip_range.get("CidrIp") == "0.0.0.0/0":
                        open_ingress.append(sg["GroupName"])
        ok = check("Boundary SGs -- no 0.0.0.0/0 ingress", not open_ingress,
                   ("Open: " + ", ".join(open_ingress[:3])) if open_ingress else "")
        passed += ok; failed += not ok
    except Exception as e:
        ok = check("Boundary SG ingress check", False, str(e))
        passed += ok; failed += not ok

    print("\\n=== Result: " + str(passed) + " passed, " + str(failed) + " failed ===\\n")
    sys.exit(0 if failed == 0 else 1)


if __name__ == "__main__":
    main()
'''

