_VALIDATION_SCRIPT = '''\
#!/usr/bin/env python3
"""AADC Agentic AI Infrastructure Validation Script — Generated by ICDEV™
Generated: {ts}

Run after `terraform apply` to verify all resources are provisioned.
Usage:
  pip install boto3
  python validate_{uid}.py --region us-gov-west-1 [--profile <aws-profile>]
"""
import argparse
import sys
import boto3


def check(label, ok, detail=""):
    status = "PASS" if ok else "FAIL"
    msg = "  [" + status + "] " + str(label)
    if detail:
        msg += " -- " + str(detail)
    print(msg)
    return ok


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--region", default="us-gov-west-1")
    parser.add_argument("--profile", default=None)
    parser.add_argument("--agent-name", default="icdev-agent")
    parser.add_argument("--env", default="dev")
    args = parser.parse_args()

    session = boto3.Session(region_name=args.region, profile_name=args.profile)
    passed = failed = 0
    agent = args.agent_name
    env = args.env
    print("\\n=== AADC Agentic AI Infrastructure Validation ===\\n")

    # Lambda orchestrator
    try:
        lam = session.client("lambda")
        fn = lam.get_function(FunctionName=f"{{env}}-aadc-{{agent}}-orchestrator")
        state = fn["Configuration"]["State"]
        ok = check("Lambda agent-orchestrator", state == "Active", state)
    except Exception as e:
        ok = check("Lambda agent-orchestrator", False, str(e))
    passed += ok; failed += not ok

    # Lambda guardrail
    try:
        lam = session.client("lambda")
        fn = lam.get_function(FunctionName=f"{{env}}-aadc-{{agent}}-guardrail")
        state = fn["Configuration"]["State"]
        ok = check("Lambda input-guardrail", state == "Active", state)
    except Exception as e:
        ok = check("Lambda input-guardrail", False, str(e))
    passed += ok; failed += not ok

    # API Gateway
    try:
        apigw = session.client("apigateway")
        apis = apigw.get_rest_apis()["items"]
        found = any(f"{{env}}-aadc-{{agent}}-api" in a["name"] for a in apis)
        ok = check("API Gateway agent API", found)
    except Exception as e:
        ok = check("API Gateway agent API", False, str(e))
    passed += ok; failed += not ok

    # DynamoDB state table
    try:
        ddb = session.client("dynamodb")
        table = ddb.describe_table(TableName=f"{{env}}-aadc-{{agent}}-state")["Table"]
        status = table["TableStatus"]
        ok = check("DynamoDB agent-state table", status == "ACTIVE", status)
    except Exception as e:
        ok = check("DynamoDB agent-state table", False, str(e))
    passed += ok; failed += not ok

    # S3 artifacts bucket
    try:
        s3 = session.client("s3")
        sts = session.client("sts")
        account_id = sts.get_caller_identity()["Account"]
        bucket = f"{{env}}-aadc-{{agent}}-artifacts-{{account_id}}"
        s3.head_bucket(Bucket=bucket)
        ok = check("S3 agent-artifacts bucket", True, bucket)
    except Exception as e:
        ok = check("S3 agent-artifacts bucket", False, str(e))
    passed += ok; failed += not ok

    # CloudWatch log group
    try:
        logs = session.client("logs")
        groups = logs.describe_log_groups(logGroupNamePrefix=f"/aadc/{{env}}/{{agent}}")["logGroups"]
        ok = check("CloudWatch agent log group", bool(groups))
    except Exception as e:
        ok = check("CloudWatch agent log group", False, str(e))
    passed += ok; failed += not ok

    print("\\n=== Result: " + str(passed) + " passed, " + str(failed) + " failed ===\\n")
    sys.exit(0 if failed == 0 else 1)


if __name__ == "__main__":
    main()
'''

