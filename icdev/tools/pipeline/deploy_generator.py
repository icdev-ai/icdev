_SCCA_INDICATOR_PREFIXES = (
    "aws-guardduty",
    "aws-securityhub",
    "aws-nfw",
    "aws-shield",
    "aws-inspector",
    "aws-macie",
    "aws-ct",
    "aws-config",
    "az-sentinel",
    "az-defender",
    "az-fw",
    "gcp-scc",
    "gcp-armor",
    "oci-guard",
    "oci-vss",
)


def _detect_scca(nodes, name):
    """Return True if the topology or pipeline name indicates SCCA/DoD scope."""
    name_lower = (name or "").lower()
    if "scca" in name_lower or "dod" in name_lower:
        return True
    for n in nodes:
        ntype = n.get("type", "")
        for prefix in _SCCA_INDICATOR_PREFIXES:
            if ntype.startswith(prefix):
                return True
    return False


