"""
Generates a layered IaC deployment bundle from a pipeline canvas graph.

Layers:
  01-network/   — VPC, subnets, security groups (delegates to existing TF generators)
  02-compute/   — K8s cluster, node groups, VMs
  03-platform/  — Container registry, secrets, KMS (managed services)
  04-tools/     — Helm releases for self-hosted tools
  05-ci-config/ — Pipeline YAML (GitLab CI, GitHub Actions, etc.)
  values/       — Helm values.yaml per tool
  ansible/      — Playbooks for VM-based tools
  deploy.sh     — Orchestrator script
  manifest.json — Deployment manifest with cost estimate

Reuses existing ICDEV generators:
  tools/infra/terraform_generator*.py (Layers 1-3)
  tools/infra/ansible_generator.py (VM tools)
  tools/pipeline/export.py (Layer 5 CI config)
"""

