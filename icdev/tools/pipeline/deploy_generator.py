def _gen_ci_config(nodes, edges, name, deps):
    """Generate CI/CD pipeline configuration.

    Returns (files, error). Previously any failure here was swallowed with a bare
    ``except: pass``, so the bundle silently shipped without a .gitlab-ci.yml while
    the manifest still counted ci_steps. Now the exception is logged at ERROR, a
    marker file is emitted into the bundle, and a structured error is returned so
    the caller can surface it in the manifest (visible failure).
    """
    files = []
    error = None
    try:
        from tools.pipeline.export import export_pipeline

        graph = {"nodes": nodes, "edges": edges}
        result = export_pipeline(graph, name, "gitlab_ci")
        files.append({"path": "05-ci-config/.gitlab-ci.yml", "content": result["content"]})
    except Exception as exc:  # noqa: BLE001 — surface, don't swallow
        logger.error("CI config generation failed for %r: %s", name, exc, exc_info=True)
        error = {"stage": "ci_config", "error": f"{type(exc).__name__}: {exc}"}
        files.append(
            {
                "path": "05-ci-config/CI_GENERATION_ERROR.txt",
                "content": (
                    f"{_CUI_HEADER}\n"
                    "# CI config generation FAILED — this bundle is missing .gitlab-ci.yml.\n"
                    f"# Error: {type(exc).__name__}: {exc}\n"
                ),
            }
        )
    return files, error


