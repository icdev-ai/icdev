def _gen_deploy_script(csp, deps, scca=False):
    """Generate the orchestrator deploy.sh script."""
    content = f"""#!/bin/bash
{_CUI_HEADER}
# Deployment orchestrator for ICDEV™ Pipeline Design Canvas
# Target CSP: {csp}
# Generated: {_NOW()}
#
# Usage:
#   ./deploy.sh plan    # Preview changes (safe, no modifications)
#   ./deploy.sh apply   # Apply changes (requires confirmation)
#   ./deploy.sh destroy # Tear down (requires confirmation)

set -euo pipefail

ACTION="${{1:-plan}}"
echo "=== ICDEV™ Pipeline Deployment ==="
echo "CSP: {csp}"
echo "Action: $ACTION"
echo ""

"""
    if scca:
        content += """# Layer 00: SCCA Foundation (deploy BEFORE all other layers)
echo "--- Layer 00: SCCA Foundation ---"
cd 00-scca-foundation
terraform init -input=false
terraform $ACTION -input=false
cd ..
echo ""

"""
    if deps["needs_vpc"]:
        content += """# Layer 1: Network
echo "--- Layer 1: Network ---"
cd 01-network
terraform init -input=false
terraform $ACTION -input=false
cd ..
echo ""

"""
    if deps["needs_k8s"] or deps["needs_vm"]:
        content += """# Layer 2: Compute
echo "--- Layer 2: Compute ---"
cd 02-compute
terraform init -input=false
terraform $ACTION -input=false
cd ..
echo ""

"""
    if deps["needs_managed"]:
        content += """# Layer 3: Platform Services
echo "--- Layer 3: Platform Services ---"
if [ -d "03-platform" ]; then
  cd 03-platform
  terraform init -input=false
  terraform $ACTION -input=false
  cd ..
fi
echo ""

"""
    if deps["helm_releases"]:
        content += """# Layer 4: DevSecOps Tools (Helm)
echo "--- Layer 4: Helm Tool Releases ---"
cd 04-tools
terraform init -input=false
terraform $ACTION -input=false
cd ..
echo ""

"""
    if deps["vm_playbooks"]:
        content += """# Ansible: VM-based tools
echo "--- Ansible Playbooks ---"
if [ "$ACTION" = "apply" ]; then
  cd ansible
  ansible-playbook -i inventory/hosts.yml playbooks/*.yml
  cd ..
fi
echo ""

"""
    content += """echo "=== Deployment $ACTION complete ==="
"""
    return {"path": "deploy.sh", "content": content}


