def _safe_name(name):
    # Allowlist [a-z0-9-] only: strips quotes/newlines/other characters so a
    # user-supplied pipeline name can never inject into generated resource names,
    # file paths, or shell/YAML that embed this value.
    lowered = str(name).lower().replace(" ", "-").replace("_", "-")
    safe = re.sub(r"[^a-z0-9-]", "-", lowered)
    safe = re.sub(r"-{2,}", "-", safe).strip("-")
    return safe[:32].strip("-") or "pipeline"


