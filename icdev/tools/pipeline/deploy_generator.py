def generate_deploy_bundle(graph, name, target_csp="auto", options=None):
    """Generate a complete IaC deployment bundle from a canvas graph.

    Args:
        graph: dict with 'nodes' and 'edges'
        name: pipeline name
        target_csp: 'auto' (detect from nodes), 'aws', 'azure', 'gcp', 'oci', 'ibm', 'on_prem'
        options: dict with optional overrides (region, environment, k8s_version, etc.)

    Returns:
        dict with 'files' (list of {path, content}), 'manifest', 'summary'
    """
    opts = options or {}
    nodes = graph.get("nodes", [])
    edges = graph.get("edges", [])
    deps = resolve_dependencies(nodes)

    csp = target_csp if target_csp != "auto" else deps["primary_csp"]
    environment = opts.get("environment", "staging")
    region = opts.get("region", _default_region(csp))
    project_name = _safe_name(name)

    files = []

    # ── Layer 00: SCCA Foundation (if DoD/SCCA topology detected) ───────
    scca_detected = _detect_scca(nodes, name)
    if scca_detected:
        files.extend(_gen_scca_foundation(csp, project_name, environment, region))

    # ── Layer 1: Network ──────────────────────────────────────────────────
    if deps["needs_vpc"]:
        files.extend(_gen_network(csp, project_name, environment, region))

    # ── Layer 2: Compute ──────────────────────────────────────────────────
    if deps["needs_k8s"]:
        files.extend(_gen_k8s_cluster(csp, project_name, environment, region, opts))
    if deps["needs_vm"]:
        files.extend(_gen_vm_instances(csp, project_name, environment, region, deps))

    # ── Layer 3: Platform Services ────────────────────────────────────────
    files.extend(_gen_platform_services(csp, project_name, environment, deps))

    # ── Layer 4: Helm Tool Releases ───────────────────────────────────────
    if deps["helm_releases"]:
        files.extend(_gen_helm_releases(deps["helm_releases"], project_name, opts))

    # ── Layer 5: CI/CD Config ─────────────────────────────────────────────
    ci_files, ci_error = _gen_ci_config(nodes, edges, name, deps)
    files.extend(ci_files)

    # ── Ansible Playbooks (VM tools) ──────────────────────────────────────
    if deps["vm_playbooks"]:
        files.extend(_gen_ansible_playbooks(deps["vm_playbooks"], project_name))

    # ── Deploy Script ─────────────────────────────────────────────────────
    files.append(_gen_deploy_script(csp, deps, scca=scca_detected))

    # ── Manifest ──────────────────────────────────────────────────────────
    node_types = [n.get("type", "") for n in nodes]
    cost = estimate_pipeline_cost(node_types, opts.get("runs_per_month", 500))
    manifest = {
        "name": name,
        "generated_at": _NOW(),
        "target_csp": csp,
        "region": region,
        "environment": environment,
        "layers": {
            "scca_foundation": scca_detected,
            "network": deps["needs_vpc"],
            "compute_k8s": deps["needs_k8s"],
            "compute_vm": deps["needs_vm"],
            "platform": deps["needs_managed"],
            "helm_tools": len(deps["helm_releases"]),
            "ci_config": len(deps["ci_steps"]),
            "ansible": len(deps["vm_playbooks"]),
        },
        "helm_releases": deps["helm_releases"],
        "managed_resources": deps["managed_resources"],
        "saas_integrations": deps["saas_integrations"],
        "ci_steps": deps["ci_steps"],
        "cost_estimate": cost,
        "node_count": len(nodes),
        "edge_count": len(edges),
    }
    # Surface a swallowed CI-generation failure so it is visible in the manifest
    # instead of the bundle silently shipping without a .gitlab-ci.yml.
    if ci_error:
        manifest["layers"]["ci_config_error"] = True
        manifest["errors"] = [ci_error]
    files.append({"path": "manifest.json", "content": json.dumps(manifest, indent=2)})

    summary = (
        f"Deployment bundle for '{name}' targeting {csp.upper()} ({region}):\n"
        f"  Network: {'yes' if deps['needs_vpc'] else 'no'}\n"
        f"  K8s cluster: {'yes' if deps['needs_k8s'] else 'no'}\n"
        f"  Helm releases: {len(deps['helm_releases'])} ({', '.join(deps['helm_releases'])})\n"
        f"  Managed resources: {len(deps['managed_resources'])}\n"
        f"  VM playbooks: {len(deps['vm_playbooks'])}\n"
        f"  CI pipeline steps: {len(deps['ci_steps'])}\n"
        f"  SaaS integrations: {len(deps['saas_integrations'])}\n"
        f"  Est. monthly cost: ${cost['total_monthly']:.2f}\n"
        f"  Total files: {len(files)}"
    )

    return {"files": files, "manifest": manifest, "summary": summary}


