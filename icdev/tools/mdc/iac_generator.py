_VALIDATION_SCRIPT = '''\
#!/usr/bin/env python3
"""MDC Migration Infrastructure Validation Script — Generated by ICDEV™
Generated: {ts}

Run after `terraform apply` to verify all resources are provisioned.
Usage:
  pip install boto3
  python validate_{uid}.py --region us-gov-west-1 [--profile <aws-profile>]
"""
import argparse
import sys
import boto3


def check(label, ok, detail=""):
    status = "PASS" if ok else "FAIL"
    msg = "  [" + status + "] " + str(label)
    if detail:
        msg += " -- " + str(detail)
    print(msg)
    return ok


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--region", default="us-gov-west-1")
    parser.add_argument("--profile", default=None)
    args = parser.parse_args()

    session = boto3.Session(region_name=args.region, profile_name=args.profile)
    passed = failed = 0
    print("\\n=== MDC Migration Infrastructure Validation ===\\n")

    # DMS replication instance
    try:
        dms = session.client("dms")
        instances = dms.describe_replication_instances(
            Filters=[{{"Name": "replication-instance-id", "Values": ["{env}-mdc-replication"]}}]
        )["ReplicationInstances"]
        ok = check("DMS replication instance", bool(instances),
                   instances[0]["ReplicationInstanceStatus"] if instances else "not found")
    except Exception as e:
        ok = check("DMS replication instance", False, str(e))
    passed += ok; failed += not ok

    # S3 staging bucket
    try:
        s3 = session.client("s3")
        sts = session.client("sts")
        account_id = sts.get_caller_identity()["Account"]
        bucket = f"{env}-mdc-migration-staging-{{account_id}}"
        s3.head_bucket(Bucket=bucket)
        ok = check("S3 migration-staging bucket", True, bucket)
    except Exception as e:
        ok = check("S3 migration-staging bucket", False, str(e))
    passed += ok; failed += not ok

    # IAM role
    try:
        iam = session.client("iam")
        role = iam.get_role(RoleName="{env}-mdc-dms-role")["Role"]
        ok = check("IAM DMS migration role", bool(role))
    except Exception as e:
        ok = check("IAM DMS migration role", False, str(e))
    passed += ok; failed += not ok

    # SSM parameter
    try:
        ssm = session.client("ssm")
        ssm.get_parameter(Name="/mdc/{env}/status")
        ok = check("SSM migration status parameter", True)
    except Exception as e:
        ok = check("SSM migration status parameter", False, str(e))
    passed += ok; failed += not ok

    print("\\n=== Result: " + str(passed) + " passed, " + str(failed) + " failed ===\\n")
    sys.exit(0 if failed == 0 else 1)


if __name__ == "__main__":
    main()
'''

