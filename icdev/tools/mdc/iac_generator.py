def generate_iac(project_id: str, run_id: str) -> dict:
    _ARTIFACTS_DIR.mkdir(parents=True, exist_ok=True)
    tf_dir = _ARTIFACTS_DIR / "terraform"
    tf_dir.mkdir(parents=True, exist_ok=True)

    uid = uuid.uuid4().hex[:8]
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    env = "migration"

    main_tf = tf_dir / f"main_{uid}.tf"
    vars_tf = tf_dir / "variables.tf"
    ansible_pb = _ARTIFACTS_DIR / f"ansible_playbook_{uid}.yml"
    validate_py = _ARTIFACTS_DIR / f"validate_{uid}.py"
    report_md = _ARTIFACTS_DIR / f"iac_report_{uid}.md"

    main_tf.write_text(_TF_MAIN.format(ts=ts), encoding="utf-8", newline="")
    vars_tf.write_text(_TF_VARIABLES, encoding="utf-8", newline="")
    ansible_pb.write_text(_ANSIBLE_PLAYBOOK.format(ts=ts), encoding="utf-8", newline="")
    validate_py.write_text(_VALIDATION_SCRIPT.format(ts=ts, uid=uid, env=env), encoding="utf-8", newline="")
    report_md.write_text(_IAC_REPORT_MD.format(ts=ts, uid=uid), encoding="utf-8", newline="")

    return {
        "uid": uid,
        "main_tf": main_tf.relative_to(_ROOT).as_posix(),
        "vars_tf": vars_tf.relative_to(_ROOT).as_posix(),
        "ansible_pb": ansible_pb.relative_to(_ROOT).as_posix(),
        "validate_py": validate_py.relative_to(_ROOT).as_posix(),
        "report_md": report_md.relative_to(_ROOT).as_posix(),
    }


def main():
    parser = argparse.ArgumentParser(description="MDC IaC Generator — Step 3")
    parser.add_argument("--project-id", default="default")
    parser.add_argument("--run-id", default="")
    parser.add_argument("--canvas", default=_CANVAS)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    try:
        result = generate_iac(args.project_id, args.run_id)

        output = {
            "gate": "PASS",
            "canvas": _CANVAS,
            "artifacts": [
                {"name": "Terraform Main", "path": result["main_tf"], "type": "tf"},
                {"name": "Terraform Variables", "path": result["vars_tf"], "type": "tf"},
                {"name": "Ansible Playbook", "path": result["ansible_pb"], "type": "yml"},
                {"name": "Validation Script", "path": result["validate_py"], "type": "py"},
                {"name": "IaC Generation Report", "path": result["report_md"], "type": "md"},
            ],
        }
        print(json.dumps(output))
        sys.exit(0)
    except Exception as exc:
        print(json.dumps({"gate": "FAIL", "canvas": _CANVAS, "error": str(exc), "artifacts": []}))
        sys.exit(1)


if __name__ == "__main__":
    main()
