# CUI // SP-CTI
"""Generated fuzz harnesses, run coverage-guided in the sandbox (icx-ent-01).

For each fuzz entry point (``module:function`` declared at registration, or proposed by the agentic review and
inside the target), this module GENERATES a harness: ``TestOneInput(text)`` calls the entry point and swallows only
the exceptions it may raise to reject input (``fuzz.expected_exceptions``); anything else escaping it is a crash.
The harness, a dictionary of the target's own string literals and the seeds are handed to
``sandbox_runtime/fuzz_runner.py`` in :meth:`SandboxExecutor.run_isolated`, no network.

Engines: atheris (libFuzzer, coverage-guided) when the pinned fuzz image (``deploy/vuln-sandbox``, atheris 3.1.0)
is present on this host, else the built-in coverage-guided fuzzer in the plain pinned image. The run records
which. A crash is only a CANDIDATE: it becomes a finding when its input replays as a PoV against the seed
(``pov.replay_pair``).
"""
from __future__ import annotations

import ast
import shutil
import subprocess  # nosec B404 — docker image inspect, fixed arguments
from pathlib import Path
from typing import Optional

from tools.vulnresearch import ledger, pov

HARNESS_TEMPLATE = '''# CUI // SP-CTI
# GENERATED by tools/vulnresearch/harness.py for {target_id} {entry} (icx-ent-01). Runs only in the sandbox.
from {module} import {function} as ENTRY

EXPECTED = ({expected},)


def TestOneInput(text):
    try:
        ENTRY(text)
    except EXPECTED:
        pass
'''


def generate(target_id: str, module: str, function: str, expected: list[str]) -> str:
    if not module.replace(".", "").replace("_", "").isalnum() or not function.replace("_", "").isalnum():
        raise ValueError(f"not an importable entry point: {module}:{function}")
    names = [e for e in expected if e.isidentifier()] or ["ValueError"]
    return HARNESS_TEMPLATE.format(target_id=target_id, entry=f"{module}:{function}", module=module,
                                   function=function, expected=", ".join(names))


def dictionary(source: str, limit: int = 64) -> list[str]:
    """The short string literals of the target's source: what a comparison in it may be waiting for."""
    out: list[str] = []
    try:
        for node in ast.walk(ast.parse(source)):
            if isinstance(node, ast.Constant) and isinstance(node.value, str) and 0 < len(node.value) <= 16:
                if node.value not in out:
                    out.append(node.value)
    except SyntaxError:
        pass
    return out[:limit]


def image_present(image: str) -> bool:
    if not image or not shutil.which("docker"):
        return False
    try:
        return subprocess.run(["docker", "image", "inspect", image], capture_output=True,  # nosec B603 B607
                              timeout=20).returncode == 0
    except Exception:  # noqa: BLE001
        return False


def fuzz(target_id: str, root: Path, entry: dict, cfg: dict, *, src_root: str = ".",
         seeds: Optional[list] = None, source: str = "") -> dict:
    """Run one generated harness. ``{status, engine, crashed, crash_input, exception, iterations, coverage, image}``."""
    fz = cfg.get("fuzz") or {}
    sb = cfg.get("sandbox") or {}
    fuzz_image = sb.get("fuzz_image") or ""
    image = fuzz_image if image_present(fuzz_image) else sb.get("image")
    sid = "fz-" + ledger.digest([target_id, entry["module"], entry["function"]])[:12]
    text = generate(target_id, entry["module"], entry["function"], fz.get("expected_exceptions") or ["ValueError"])
    spec = {"id": sid, "harness": "harness_gen.py", "src_root": src_root,
            "seeds": [str(s) for s in (seeds or ["", "a"])], "dictionary": dictionary(source),
            "iterations": int(fz.get("iterations") or 2000), "seed": int(fz.get("seed") or 1),
            "max_input_len": int(fz.get("max_input_len") or 256),
            "engine": "auto" if image == fuzz_image else "builtin"}
    run = pov.run_in_sandbox("fuzz_runner.py", spec, target_root=root, image=image,
                             extra_files={"harness_gen.py": text})
    res = run.get("result") or {}
    return {"status": run["status"], "engine": res.get("engine"), "crashed": bool(res.get("crashed")),
            "crash_input": res.get("crash_input"), "exception": res.get("exception"),
            "iterations": res.get("iterations"), "coverage": res.get("coverage"), "image": image,
            "harness_digest": ledger.digest(text), "seeds": spec["seeds"], "detail": run.get("stderr", "")[-300:]}
